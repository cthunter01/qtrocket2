/// The number of values of @p pins, over all seeds.
template <class Pin>
[[nodiscard]] std::size_t pinnedValueCount(std::span<const Pin> pins)
{
    std::size_t count = 0;
    for (const Pin& pin : pins)
    {
        count += pin.values.size();
    }
    return count;
}

/// The first index at which nextDouble() of a generator seeded as @p pin differs from Java's
/// value, or the number of values when none does.
[[nodiscard]] std::size_t firstDoubleMismatch(const DoublePin& pin)
{
    JavaRandom random(pin.seed);
    for (std::size_t i = 0; i < pin.values.size(); i++)
    {
        if (random.nextDouble() != pin.values.at(i))
        {
            return i;
        }
    }
    return pin.values.size();
}

/// As firstDoubleMismatch(), for nextInt().
[[nodiscard]] std::size_t firstIntMismatch(const IntPin& pin)
{
    JavaRandom random(pin.seed);
    for (std::size_t i = 0; i < pin.values.size(); i++)
    {
        if (random.nextInt() != pin.values.at(i))
        {
            return i;
        }
    }
    return pin.values.size();
}

/// As firstDoubleMismatch(), for next(1), next(2), ... next(32).
[[nodiscard]] std::size_t firstBitsMismatch(const BitsPin& pin)
{
    JavaRandom random(pin.seed);
    for (std::size_t i = 0; i < pin.values.size(); i++)
    {
        if (random.next(static_cast<int>(i) + 1) != pin.values.at(i))
        {
            return i;
        }
    }
    return pin.values.size();
}

/// Whether the next @p count ints of @p a and @p b are the same.
[[nodiscard]] bool drawTheSameInts(JavaRandom a, JavaRandom b, int count = 20)
{
    for (int i = 0; i < count; i++)
    {
        if (a.nextInt() != b.nextInt())
        {
            return false;
        }
    }
    return true;
}

/// How many of the next @p count doubles of @p random are outside [0, 1) or not a multiple of
/// 2^-53.
[[nodiscard]] int badDoubles(JavaRandom random, int count)
{
    int bad = 0;
    for (int i = 0; i < count; i++)
    {
        const double value  = random.nextDouble();
        const double scaled = value * 0x1.0p53;
        const bool   good   = value >= 0.0 && value < 1.0 &&
                              scaled == static_cast<double>(static_cast<std::int64_t>(scaled));
        bad += good ? 0 : 1;
    }
    return bad;
}

/// How many of @p count draws of 1, 2, ... 31 bits (in turn) of @p random are negative or do
/// not fit their width.
[[nodiscard]] int badBits(JavaRandom random, int count)
{
    int bad = 0;
    for (int i = 0; i < count; i++)
    {
        const int          bits  = (i % 31) + 1;
        const std::int32_t value = random.next(bits);
        const bool         good  = value >= 0 && std::int64_t{value} < (std::int64_t{1} << bits);
        bad += good ? 0 : 1;
    }
    return bad;
}


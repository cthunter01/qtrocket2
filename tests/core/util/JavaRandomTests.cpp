// RandomProbe "mixed": new Random(2024), then nextInt(), nextDouble(), nextInt(), nextDouble(),
// setSeed(-5), nextDouble(), nextInt().
TEST(JavaRandom, IntsAndDoublesShareOneSequenceAndSetSeedStartsAnother)
{
    JavaRandom random(2024);
    EXPECT_EQ(random.nextInt(), -1638729195);
    EXPECT_EQ(random.nextDouble(), 0.7359062461301408);
    EXPECT_EQ(random.nextInt(), -939999476);
    EXPECT_EQ(random.nextDouble(), 0.9309788145598492);
    random.setSeed(-5);
    EXPECT_EQ(random.nextDouble(), 0.26930095796932485);
    EXPECT_EQ(random.nextInt(), 1434915906);

    // setSeed() gives the sequence of a new generator with that seed.
    random.setSeed(-5);
    EXPECT_TRUE(drawTheSameInts(random, JavaRandom(-5)));
}

TEST(JavaRandom, OnlyTheLow48BitsOfTheScrambledSeedCount)
{
    // Long.MIN_VALUE has no bit among the low 48: Java draws the sequence of the seed 0 (the
    // pins say the same: their first two values are equal).
    EXPECT_TRUE(drawTheSameInts(JavaRandom(kLongMin), JavaRandom(0)));
    // Long.MAX_VALUE has all of the low 48 bits, as -1 has.
    EXPECT_TRUE(
        drawTheSameInts(JavaRandom(std::numeric_limits<std::int64_t>::max()), JavaRandom(-1)));
    EXPECT_FALSE(drawTheSameInts(JavaRandom(0), JavaRandom(-1)));
}

// A Java int seed is widened with its sign: (long) (-7 ^ 0x23E3A01F) is -602120218.
TEST(JavaRandom, AnIntSeedIsWidenedWithItsSign)
{
    const std::int32_t jitterSeed = -7 ^ 0x23E3A01F;
    EXPECT_EQ(jitterSeed, -602120218);

    EXPECT_TRUE(drawTheSameInts(JavaRandom(jitterSeed), JavaRandom(std::int64_t{-602120218})));
    // The same 32 bits without the sign: another seed, and another sequence.
    const auto unsignedBits = static_cast<std::int64_t>(static_cast<std::uint32_t>(jitterSeed));
    EXPECT_FALSE(drawTheSameInts(JavaRandom(jitterSeed), JavaRandom(unsignedBits)));
}

// RandomProbe "the jitter of seed 0": what AbstractRKSimulationStepper adds to Cm and Cyaw,
// PITCH_YAW_RANDOM * 2 * (random.nextDouble() - 0.5), for the first three force calculations of
// a simulation with the random seed 0 (Cm first, Cyaw second).
TEST(JavaRandom, TheJitterOfTheRandomSeedZeroIsJavas)
{
    JavaRandom random(0 ^ 0x23E3A01F);
    EXPECT_EQ(0.0005 * 2 * (random.nextDouble() - 0.5), -1.9802439270403228E-4);
    EXPECT_EQ(0.0005 * 2 * (random.nextDouble() - 0.5), -4.611990164530595E-4);
    EXPECT_EQ(0.0005 * 2 * (random.nextDouble() - 0.5), -4.7749226758489217E-4);
    EXPECT_EQ(0.0005 * 2 * (random.nextDouble() - 0.5), 3.046444384204647E-4);
    EXPECT_EQ(0.0005 * 2 * (random.nextDouble() - 0.5), -1.0948616792159416E-5);
    EXPECT_EQ(0.0005 * 2 * (random.nextDouble() - 0.5), -2.630017182214638E-4);
}


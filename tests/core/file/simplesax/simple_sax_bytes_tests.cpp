/// A document of @p count <p> elements after an <a>, and then @p tail.
[[nodiscard]] std::string longDocument(std::string_view head, std::size_t count,
                                       std::string_view tail)
{
    std::string document(head);
    document += "<r><a>1</a>";
    for (std::size_t i = 0; i < count; i++)
    {
        document += "<p>0123456789</p>";
    }
    document += tail;
    return document;
}

/// The calls for the start of longDocument() with @p count <p> elements read.
[[nodiscard]] std::string longLog(std::size_t count)
{
    std::string log = "open r | open a | end a | close a [1] | ";
    for (std::size_t i = 0; i < count; i++)
    {
        log += "open p | end p | close p [0123456789] | ";
    }
    return log;
}

TEST(SimpleSaxBytes, AnInvalidByteFarIntoADocumentComesAfterEveryElementBeforeIt)
{
    // 19 kB of elements, beyond the JDK's buffers of 8192 characters: measured, its handlers
    // see all 1200 elements and the start of the one that holds the byte.
    EXPECT_EQ(readBytes(longDocument("", 1200, "<c>\xFF</c></r>")),
              longLog(1200) + "open c | => PARSE: Invalid byte 1 of 1-byte UTF-8 sequence.");
    // An error in the XML before the byte is the one that is reported.
    EXPECT_EQ(readBytes(longDocument("", 1200, "</q><c>\xFF</c></r>")),
              longLog(1200) +
                  "=> PARSE: The element type \"r\" must be terminated by the "
                  "matching end-tag \"</r>\".");
}

TEST(SimpleSaxBytes, AHighByteFarIntoAnAsciiDocumentIsRefusedBeforeAnyHandler)
{
    // Not the JDK's: its ASCII reader refuses the block of up to 8192 bytes the byte is in, and
    // its handlers have seen the 963 <p> elements of the blocks before (measured).
    EXPECT_EQ(readBytes(longDocument("<?xml version='1.0' encoding='US-ASCII'?>", 1200,
                                     "<c>\xE9</c></r>")),
              "=> PARSE: Byte \"233\" is not a member of the (7-bit) ASCII character set.");
}

TEST(SimpleSaxBytes, AFailureOfAHandlerBeforeAnInvalidByteComesFirst)
{
    EXPECT_EQ(readBytes("<r><a>1</a><b/><c>\xFF</c></r>", "b"),
              "open r | open a | end a | close a [1] | open b | => PARSE: fail b");
    // A handler that would fail after the byte is never asked.
    EXPECT_EQ(readBytes("<r><a>1</a>\xFF<b/></r>", "b"),
              "open r | open a | end a | close a [1] | => PARSE: Invalid byte 1 of 1-byte UTF-8 "
              "sequence.");
}

TEST(SimpleSaxBytes, TheErrorCodesTellTheKindsOfFailureApart)
{
    RecordingHandler handler;
    WarningSet       warnings;
    const auto       code = [&handler, &warnings](std::string_view document) {
        return SimpleSax::readXml(QtRocket::stringToBytes(document), handler, warnings)
            .error()
            .code;
    };
    // Malformed XML and bytes that are no text: what a loader calls "Malformed XML in input.".
    EXPECT_EQ(code("<r>"), ErrorCode::PARSE);
    EXPECT_EQ(code("<r>\xFF</r>"), ErrorCode::PARSE);
    EXPECT_EQ(code("<?xml version='1.0' encoding='a b'?><r/>"), ErrorCode::PARSE);
    // An encoding this does not read: Java's IOException, "I/O error: <name>" in a loader.
    EXPECT_EQ(code("<?xml version='1.0' encoding='klingon'?><r/>"), ErrorCode::IO);
    EXPECT_EQ(code("\xFE\xFF\x00<\x00r\x00/\x00>"sv), ErrorCode::IO);
}

TEST(SimpleSaxBytes, TheTextEntryStillReadsMalformedBytesAsReplacementCharacters)
{
    // The two entries differ on purpose: a character stream has been decoded by someone else.
    RecordingHandler handler;
    WarningSet       warnings;
    EXPECT_TRUE(SimpleSax::readXml("<r>caf\xE9</r>"sv, handler, warnings).has_value());
    EXPECT_EQ(handler.log,
              (std::vector<std::string>{"open r", "end r", "close r [caf\xEF\xBF\xBD]"}));
    // And it does not look at the declared encoding.
    RecordingHandler latin1;
    EXPECT_TRUE(SimpleSax::readXml("<?xml version='1.0' encoding='ISO-8859-1'?><r>\xC3\xA9</r>"sv,
                                   latin1, warnings)
                    .has_value());
    EXPECT_EQ(latin1.log, (std::vector<std::string>{"open r", "end r", "close r [\xC3\xA9]"}));
}


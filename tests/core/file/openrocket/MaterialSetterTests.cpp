[[nodiscard]] std::string readBodyTube(ApplicationSetterFixture& fixture, const RocketComponent& c)
{
    return listInOrder({as<BodyTube>(c).getMaterial().toStorableString(),
                        flag(as<BodyTube>(c).getMaterial().isUserDefined()),
                        flag(as<BodyTube>(c).getMaterial().isDocumentMaterial()),
                        documentMaterialsOf(fixture.document())});
}


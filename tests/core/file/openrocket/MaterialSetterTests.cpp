// What <material>, <filletmaterial> and <linematerial> do to a component, as OpenRocket's
// MaterialSetter does it. kJava holds OpenRocket's answers (the probe SpecialSetterProbe of
// tier 9b, part R2; see SetterTestSupport.h). A row applies its elements through the entries of
// the setter table to a new component in a document, and compares the component's material (its
// storable string "TYPE|name|density|shear modulus|group", whether it is user-defined and
// whether it is a material of the document), the materials the document holds afterwards, in
// the order a save writes them, and the warnings.
//
// The application's materials are OpenRocket's built-in ones, as in the probe. A new body tube
// is of "Cardboard", a shock cord and a parachute's lines of "Elastic cord (round 2 mm, 1/16
// in)" and a parachute or streamer of "Ripstop nylon".


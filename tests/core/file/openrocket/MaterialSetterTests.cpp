/// What <material> with @p attributes and the name @p text gives a body tube when the
/// application has no materials at all (a null pointer in the context): readBodyTube(), then the
/// warnings in brackets.
[[nodiscard]] std::string withoutApplicationMaterials(std::string_view attributes,
                                                      std::string_view text)
{
    ApplicationSetterFixture fixture;
    fixture.context().setApplicationMaterials(nullptr);
    RocketComponent&    tube   = fixture.make(ComponentKind::BODY_TUBE);
    const Setter* const setter = setterOfKey("ExternalComponent:material");
    WarningSet          warnings;
    if (setter == nullptr ||
        !setter->set(tube, text, attributesOf(attributes), warnings, fixture.context()).has_value())
    {
        return "no setter, or it failed";
    }
    return withWarnings(readBodyTube(fixture, tube), warnings);
}

// OpenRocket always has its material databases; QtRocket's context may have none. The lookups
// then find nothing: the material of the application's name becomes one of the document, with
// the name translated as ever and nothing but what the element says.
TEST(MaterialSetter, WithoutApplicationMaterialsEveryMaterialIsTheDocuments)
{
    EXPECT_EQ(withoutApplicationMaterials("type=bulk|density=170.0", "Balsa"),
              "BULK|Balsa|170.0|0.0|Custom, true, true, BULK|Balsa|170.0|0.0|Custom");
    EXPECT_EQ(
        withoutApplicationMaterials("density=1250.0|shearModulus=2.4E9|group=Plastics", "PLA"),
        "BULK|PLA - 100% infill|1250.0|2.4E9|Plastics, true, true, "
        "BULK|PLA - 100% infill|1250.0|2.4E9|Plastics");
    // The group of older files that is looked up in the application's materials: OTHER.
    EXPECT_EQ(withoutApplicationMaterials("density=5|group=ThreadsLines", "Cord"),
              "BULK|Cord|5.0|0.0|Other, true, true, BULK|Cord|5.0|0.0|Other");
    EXPECT_EQ(withoutApplicationMaterials("density=x", "Balsa"),
              "BULK|Cardboard|680.0|4.0E8|PaperProducts, false, false,  "
              "[Illegal material specification, ignoring.]");
}

/// What a setter of a material of @p type, made by the test, hands its function for the element:
/// the material (describeMaterial()) or "nothing", then the warnings in brackets.
[[nodiscard]] std::string materialHandedOver(Material::Type type, std::string_view attributes,
                                             std::string_view text)
{
    std::string          handed = "nothing";
    const MaterialSetter setter(
        [&handed](RocketComponent& /*component*/, const Material& material) {
            handed = describeMaterial(material);
        },
        type);
    ApplicationSetterFixture fixture;
    WarningSet               warnings;
    if (!setter
             .set(fixture.setters().tube(), text, attributesOf(attributes), warnings,
                  fixture.context())
             .has_value())
    {
        return "the setter failed";
    }
    return withWarnings(std::move(handed), warnings);
}

// The type is the setter's, not the element's: the lookup is among the materials of that type,
// and the element's type="" is only checked against it.
TEST(MaterialSetter, LooksTheMaterialUpAmongThoseOfItsType)
{
    EXPECT_EQ(materialHandedOver(Material::Type::SURFACE, "density=0.067", "Ripstop nylon"),
              "SURFACE|Ripstop nylon|0.067|0.0|Fabrics, false, false");
    EXPECT_EQ(
        materialHandedOver(Material::Type::SURFACE, "type=surface|density=0.067", "Ripstop nylon"),
        "SURFACE|Ripstop nylon|0.067|0.0|Fabrics, false, false");
    // No line material has that name: a line material of the document.
    EXPECT_EQ(materialHandedOver(Material::Type::LINE, "density=0.067", "Ripstop nylon"),
              "LINE|Ripstop nylon|0.067|0.0|Custom, true, true");
    EXPECT_EQ(
        materialHandedOver(Material::Type::LINE, "type=surface|density=0.067", "Ripstop nylon"),
        "nothing [Illegal material type specified, ignoring.]");
    EXPECT_EQ(materialHandedOver(Material::Type::BULK, "type=bulk", "Balsa"),
              "nothing [Illegal material specification, ignoring.]");
}


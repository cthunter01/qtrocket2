/// A tube fin set built as the probe built it, with what owns it.
struct TubeFins
{
    std::unique_ptr<Rocket>     rocket;  ///< with a stage and a body tube; null without a parent
    std::unique_ptr<TubeFinSet> orphan;  ///< the tube fin set when it has no parent
    TubeFinSet*                 fins{nullptr};
};

[[nodiscard]] TubeFins makeTubeFins(bool onBody, int finCount, double chord,
                                    double fixedOuterRadius, double thickness)
{
    TubeFins made;
    if (onBody)
    {
        made.rocket       = std::make_unique<Rocket>();
        AxialStage& stage = made.rocket->addChild(std::make_unique<AxialStage>());
        BodyTube&   body  = stage.addChild(std::make_unique<BodyTube>(0.3, 0.025));
        made.fins         = &body.addChild(std::make_unique<TubeFinSet>());
    }
    else
    {
        made.orphan = std::make_unique<TubeFinSet>();
        made.fins   = made.orphan.get();
    }
    made.fins->setFinCount(finCount);
    made.fins->setLength(chord);
    if (!std::isnan(fixedOuterRadius))
    {
        made.fins->setOuterRadius(fixedOuterRadius);
    }
    if (!std::isnan(thickness))
    {
        made.fins->setThickness(thickness);
    }
    if (made.rocket != nullptr)
    {
        made.rocket->enableEvents();
    }
    return made;
}

[[nodiscard]] TubeFins makeTubeFins(const TubeFinCase& c)
{
    return makeTubeFins(c.onBody, c.finCount, c.chord, c.fixedOuterRadius, c.thickness);
}

/// Fresh conditions with the reference length, theta and roll rate of the pins.
[[nodiscard]] FlightConditions conditionsAt(double mach, double aoaDeg)
{
    FlightConditions conditions;
    conditions.setRefLength(kRefLength);
    conditions.setMach(mach);
    conditions.setAOA(MathUtil::deg2rad(aoaDeg));
    conditions.setTheta(kTheta);
    conditions.setRollRate(kRollRate);
    return conditions;
}

/// The fixed-text warning of a kind; null for none.
[[nodiscard]] const Warning* warningOf(TubeWarning kind)
{
    switch (kind)
    {
        case TubeWarning::NONE:
            return nullptr;
        case TubeWarning::ISOLATED:
            return &Warning::kTubeIsolated;
        case TubeWarning::SEPARATION:
            return &Warning::kTubeSeparation;
        case TubeWarning::OVERLAP:
            return &Warning::kTubeOverlap;
    }
    return nullptr;
}

/// Whether @p warnings holds exactly the geometry warning @p kind, with @p fins as its source.
[[nodiscard]] bool holdsOnly(const WarningSet& warnings, TubeWarning kind, const TubeFinSet& fins)
{
    const Warning* expected = warningOf(kind);
    if (expected == nullptr)
    {
        return warnings.empty();
    }
    if (warnings.size() != 1)
    {
        return false;
    }
    const Warning& warning = *warnings.begin();
    return warning.messageDescription() == expected->messageDescription() &&
           warning.priority() == expected->priority() && warning.sources().size() == 1 &&
           warning.sources().front().id == fins.getId() &&
           warning.sources().front().name == fins.getName();
}

/// Compares a value with the one OpenRocket printed: within 1e-12 of the value itself, so a small
/// value is held as strictly as a large one and a zero must be a zero.
/// JavaValueDifferences::number(), which also allows an absolute 1e-15, only decides for NaN (NaN
/// with NaN) and the infinities.
void pin(JavaValueDifferences& differences, std::string_view field, double expected, double actual)
{
    const bool finite = std::isfinite(expected) && std::isfinite(actual);
    const bool within =
        std::abs(actual - expected) <= 1e-12 * std::max(std::abs(expected), std::abs(actual));
    if (finite && !within)
    {
        differences.problem(std::format("{}: expected {}, got {}", field, expected, actual));
    }
    else
    {
        differences.number(field, expected, actual);
    }
}

/// Whether the CP position of a case at @p mach is Java's double exactly: outside the transonic
/// interpolation (Mach 0.5 to 2, which may raise to a power) it is the result of additions,
/// multiplications, divisions and one square root only, when the tube's radii are given (an
/// automatic outer radius goes through a sine, a missing wall thickness makes everything NaN).
/// At Mach 2 exactly this tells the supersonic formula from the interpolation that ends there.
[[nodiscard]] bool isExactCpPosition(const TubeFinCase& c, double mach)
{
    return (mach <= 0.5 || mach >= 2) && !std::isnan(c.fixedOuterRadius) &&
           !std::isnan(c.thickness);
}

/// Compares the forces at kMachs[m] and kAoas[a] with Java's.
void compareForces(JavaValueDifferences& differences, TubeFinSetCalc& calc, const TubeFinCase& c,
                   const TubeFinSet& fins, std::size_t m, std::size_t a)
{
    const FlightConditions conditions = conditionsAt(kMachs.at(m), kAoas.at(a));
    WarningSet             warnings;
    AerodynamicForces      forces;
    calc.calculateNonaxialForces(conditions, Transformation::rotateX(kRotation), forces, warnings);

    const std::array<double, 7>& row = c.rows.at(m);
    const std::string            at  = std::format("Mach {} AoA {}", kMachs.at(m), kAoas.at(a));
    pin(differences, at + " CP x", row[0], forces.getCP().x);
    if (isExactCpPosition(c, kMachs.at(m)) && forces.getCP().x != row[0])
    {
        differences.problem(
            std::format("{} CP x: expected exactly {}, got {}", at, row[0], forces.getCP().x));
    }
    pin(differences, at + " CNa", c.cna, forces.getCP().weight);
    pin(differences, at + " CN", c.cn.at(a), forces.getCN());
    pin(differences, at + " Cm", row.at(3 + a), forces.getCm());
    pin(differences, at + " CrollDamp", row[1], forces.getCrollDamp());
    pin(differences, at + " CrollForce", c.crollForce, forces.getCrollForce());
    // Java: Croll = CrollForce - CrollDamp, the same subtraction of the same doubles.
    pin(differences, at + " Croll", c.crollForce - row[1], forces.getCroll());
    // The CP is on the axis (NaN when CNa is).
    const double offAxis = std::isnan(c.cna) ? kNaN : 0.0;
    pin(differences, at + " CP y", offAxis, forces.getCP().y);
    pin(differences, at + " CP z", offAxis, forces.getCP().z);
    if (forces.getCside() != 0 || forces.getCyaw() != 0)
    {
        differences.problem(at + ": a side force or yaw coefficient is not 0");
    }
    if (!holdsOnly(warnings, c.warning, fins))
    {
        differences.problem(at + ": warnings " + warnings.toString());
    }
}

/// Compares the pressure drag at kMachs[m] with Java's.
void comparePressure(JavaValueDifferences& differences, TubeFinSetCalc& calc, const TubeFinCase& c,
                     const TubeFinSet& fins, std::size_t m)
{
    const double mach = kMachs.at(m);
    WarningSet   warnings;
    pin(differences, std::format("pressure CD at Mach {}", mach), c.rows.at(m)[2],
        calc.calculatePressureCD(conditionsAt(mach, 0),
                                 BarrowmanDragCalculator::calculateStagnationCD(mach),
                                 BarrowmanDragCalculator::calculateBaseCD(mach), warnings));
    if (!holdsOnly(warnings, c.warning, fins))
    {
        differences.problem(std::format("pressure CD at Mach {}: warnings ", mach) +
                            warnings.toString());
    }
}

/// What differs between Java's values and the calculator's for a case; empty when nothing does.
[[nodiscard]] std::string differencesOf(const TubeFinCase& c)
{
    const TubeFins       made = makeTubeFins(c);
    TubeFinSetCalc       calc{*made.fins};
    JavaValueDifferences differences;
    pin(differences, "outer radius", c.outerRadius, made.fins->getOuterRadius());
    for (std::size_t m = 0; m < kMachs.size(); m++)
    {
        for (std::size_t a = 0; a < kAoas.size(); a++)
        {
            compareForces(differences, calc, c, *made.fins, m, a);
        }
        comparePressure(differences, calc, c, *made.fins, m);
    }
    WarningSet warnings;
    pin(differences, "friction CD", c.frictionCD,
        calc.calculateFrictionCD(conditionsAt(0.3, 0), kCf, warnings));
    if (!warnings.empty())
    {
        differences.problem("the friction drag added warnings: " + warnings.toString());
    }
    if (!holdsOnly(calc.getGeometryWarnings(), c.warning, *made.fins))
    {
        differences.problem("geometry warnings " + calc.getGeometryWarnings().toString());
    }
    return differences.text();
}


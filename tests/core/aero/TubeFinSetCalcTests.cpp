/// The forces of @p calc at a Mach number, an angle of attack in radians and a roll rate.
[[nodiscard]] AerodynamicForces forcesAt(TubeFinSetCalc& calc, double mach, double aoa,
                                         double rollRate, WarningSet& warnings)
{
    FlightConditions conditions;
    conditions.setRefLength(kRefLength);
    conditions.setMach(mach);
    conditions.setAOA(aoa);
    conditions.setRollRate(rollRate);
    AerodynamicForces forces;
    calc.calculateNonaxialForces(conditions, Transformation::kIdentity, forces, warnings);
    return forces;
}

TEST(TubeFinSetCalc, NormalForceIsHeldBeyondTheStallAngle)
{
    const TubeFins made = makeTubeFins(true, 6, 0.06, kNaN, 0.001);
    TubeFinSetCalc calc{*made.fins};
    WarningSet     warnings;
    const double   stall = 20 * std::numbers::pi / 180;

    const AerodynamicForces at     = forcesAt(calc, 0.3, stall, 0, warnings);
    const AerodynamicForces beyond = forcesAt(calc, 0.3, 1.0, 0, warnings);
    const double            cna    = at.getCP().weight;
    EXPECT_GT(cna, 0.0);
    EXPECT_EQ(at.getCN(), cna * stall);
    EXPECT_EQ(beyond.getCN(), cna * stall);
    EXPECT_EQ(beyond.getCm(), at.getCm());
    // Below it CN follows the angle.
    EXPECT_EQ(forcesAt(calc, 0.3, 0.1, 0, warnings).getCN(), cna * 0.1);
    // The CP does not move with the angle of attack.
    EXPECT_EQ(beyond.getCP().x, at.getCP().x);
    EXPECT_EQ(beyond.getCP().weight, cna);
}

TEST(TubeFinSetCalc, RollDampingFollowsTheRollRate)
{
    const TubeFins made = makeTubeFins(true, 6, 0.06, kNaN, 0.001);
    TubeFinSetCalc calc{*made.fins};
    WarningSet     warnings;

    // Without a roll rate there is no roll moment (a tube is never canted).
    const AerodynamicForces still = forcesAt(calc, 0.3, 0.05, 0, warnings);
    EXPECT_EQ(still.getCrollForce(), 0.0);
    EXPECT_EQ(still.getCrollDamp(), 0.0);
    EXPECT_EQ(still.getCroll(), 0.0);

    // The damping is proportional to the roll rate and opposes it, also beyond the stall angle.
    const AerodynamicForces rolling = forcesAt(calc, 0.3, 0.05, 4, warnings);
    const AerodynamicForces faster  = forcesAt(calc, 0.3, 0.05, 8, warnings);
    const AerodynamicForces stalled = forcesAt(calc, 0.3, 0.5, 4, warnings);
    EXPECT_GT(rolling.getCrollDamp(), 0.0);
    EXPECT_EQ(faster.getCrollDamp(), 2 * rolling.getCrollDamp());
    EXPECT_EQ(rolling.getCroll(), -rolling.getCrollDamp());
    EXPECT_EQ(forcesAt(calc, 0.3, 0.05, -4, warnings).getCroll(), rolling.getCrollDamp());
    EXPECT_EQ(stalled.getCrollForce(), 0.0);
    EXPECT_EQ(stalled.getCrollDamp(), rolling.getCrollDamp());
    EXPECT_TRUE(warnings.empty());
}

TEST(TubeFinSetCalc, AddsItsGeometryWarningOnceToTheCallersSet)
{
    const TubeFins made = makeTubeFins(true, 3, 0.06, 0.01, 0.001);  // apart
    TubeFinSetCalc calc{*made.fins};
    ASSERT_TRUE(holdsOnly(calc.getGeometryWarnings(), TubeWarning::SEPARATION, *made.fins));

    WarningSet warnings;
    warnings.add(Warning::kSupersonic);
    static_cast<void>(forcesAt(calc, 0.3, 0.05, 0, warnings));
    static_cast<void>(forcesAt(calc, 2.0, 0.05, 0, warnings));
    FlightConditions conditions;
    static_cast<void>(calc.calculatePressureCD(conditions, 0.9, 0.2, warnings));
    EXPECT_EQ(warnings.size(), 2U);
    EXPECT_TRUE(warnings.contains(Warning::kSupersonic));
    const Message& added = *std::next(warnings.begin());
    EXPECT_EQ(added.messageDescription(), Warning::kTubeSeparation.messageDescription());
    ASSERT_EQ(added.sources().size(), 1U);
    EXPECT_EQ(added.sources().front().id, made.fins->getId());
    // The fixed-text warning itself has no source, so it is another warning.
    EXPECT_FALSE(warnings.contains(Warning::kTubeSeparation));

    // The friction drag adds none.
    WarningSet frictionWarnings;
    static_cast<void>(calc.calculateFrictionCD(conditions, kCf, frictionWarnings));
    EXPECT_TRUE(frictionWarnings.empty());
}

TEST(TubeFinSetCalc, CopiesTheGeometryWhenItIsMade)
{
    const TubeFins          made = makeTubeFins(true, 3, 0.06, 0.01, 0.001);
    TubeFinSetCalc          kept{*made.fins};
    WarningSet              warnings;
    const FlightConditions  conditions = conditionsAt(1.5, 2);
    const AerodynamicForces before     = forcesAt(kept, 1.5, 0.05, 3, warnings);
    const double            pressure   = kept.calculatePressureCD(conditions, 1.3, 0.17, warnings);
    const double            friction   = kept.calculateFrictionCD(conditions, kCf, warnings);

    made.fins->setLength(0.1);
    made.fins->setOuterRadius(0.03);
    made.fins->setThickness(0.003);
    made.fins->setFinCount(1);

    WarningSet              later;
    const AerodynamicForces after = forcesAt(kept, 1.5, 0.05, 3, later);
    EXPECT_EQ(after.getCP().x, before.getCP().x);
    EXPECT_EQ(after.getCP().weight, before.getCP().weight);
    EXPECT_EQ(after.getCN(), before.getCN());
    EXPECT_EQ(after.getCrollDamp(), before.getCrollDamp());
    EXPECT_EQ(kept.calculatePressureCD(conditions, 1.3, 0.17, later), pressure);
    EXPECT_EQ(kept.calculateFrictionCD(conditions, kCf, later), friction);
    // The warning found at construction stays, too.
    EXPECT_TRUE(holdsOnly(later, TubeWarning::SEPARATION, *made.fins));

    TubeFinSetCalc renewed{*made.fins};
    WarningSet     renewedWarnings;
    EXPECT_NE(forcesAt(renewed, 1.5, 0.05, 3, renewedWarnings).getCP().weight,
              before.getCP().weight);
    EXPECT_TRUE(holdsOnly(renewedWarnings, TubeWarning::ISOLATED, *made.fins));
}

TEST(TubeFinSetCalc, WarningDependsOnTheSeparationOfTheTubes)
{
    // Six tubes around a body of the same radius touch each other exactly.
    const TubeFins touching = makeTubeFins(true, 6, 0.06, kNaN, 0.001);
    EXPECT_TRUE(TubeFinSetCalc{*touching.fins}.getGeometryWarnings().empty());

    // More than MathUtil::kEpsilon apart or overlapping is reported; less is not.
    const TubeFins apart = makeTubeFins(true, 6, 0.06, 0.025 - 1e-8, 0.001);
    EXPECT_TRUE(holdsOnly(TubeFinSetCalc{*apart.fins}.getGeometryWarnings(),
                          TubeWarning::SEPARATION, *apart.fins));
    const TubeFins overlapping = makeTubeFins(true, 6, 0.06, 0.025 + 1e-8, 0.001);
    EXPECT_TRUE(holdsOnly(TubeFinSetCalc{*overlapping.fins}.getGeometryWarnings(),
                          TubeWarning::OVERLAP, *overlapping.fins));
    const TubeFins close = makeTubeFins(true, 6, 0.06, 0.025 - 1e-9, 0.001);
    EXPECT_TRUE(TubeFinSetCalc{*close.fins}.getGeometryWarnings().empty());

    // A single tube is isolated whatever its radius.
    const TubeFins single = makeTubeFins(true, 1, 0.06, 0.04, 0.001);
    EXPECT_TRUE(holdsOnly(TubeFinSetCalc{*single.fins}.getGeometryWarnings(), TubeWarning::ISOLATED,
                          *single.fins));
}


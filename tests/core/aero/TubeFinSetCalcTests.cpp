/// TubeFinSetCalcTest.EPSILON.
constexpr double kEpsilon = 0.000001;

/// TubeFinSetCalcTest.relativeCP(): the tube-fin CP as a fraction of its chord.
[[nodiscard]] double relativeCP(const TubeFinSet& tubeFins, const Rocket& rocket, double mach)
{
    const FlightConfiguration& config = rocket.getSelectedConfiguration();
    FlightConditions           conditions{config};
    conditions.setMach(mach);
    AerodynamicForces forces;
    TubeFinSetCalc    calc{tubeFins};
    WarningSet        warnings;
    calc.calculateNonaxialForces(conditions, Transformation::kIdentity, forces, warnings);
    return forces.getCP().x / tubeFins.getLength();
}

/// The tube fin set both tests add to the body tube of the Estes Alpha III (Java's (BodyTube)
/// rocket.getChild(0).getChild(1)), with this outer radius.
TubeFinSet& addTubeFins(const TestEstesAlphaIII& alpha, double outerRadius)
{
    EXPECT_EQ(&alpha.rocket->getChild(0).getChild(1), alpha.body);
    auto        owner    = std::make_unique<TubeFinSet>();
    TubeFinSet& tubeFins = *owner;
    tubeFins.setOuterRadius(outerRadius);
    tubeFins.setThickness(0.002);
    tubeFins.setLength(0.05);
    alpha.body->addChild(std::move(owner));
    return tubeFins;
}

// TubeFinSetCalcTest.testTransonicCPUsesInterpolationPolynomial
TEST(TubeFinSetCalc, TransonicCPUsesInterpolationPolynomial)
{
    const TestEstesAlphaIII alpha;
    const TubeFinSet&       tubeFins = addTubeFins(alpha, 0.027);

    // AR = 2*innerRadius/chord = 1, for which p(1) is about 0.32124.
    const double cp = relativeCP(tubeFins, *alpha.rocket, 1.0);
    EXPECT_NEAR(cp, 0.3212384847, kEpsilon)
        << "Tube-fin CP should follow the transonic interpolation polynomial";
    EXPECT_GT(cp, 0.25) << "The initialized polynomial must move this tube-fin CP aft";
}

/// The loop of testLowAspectRatioTubeFinCPIsFiniteAndMonotone: Mach 0.5 to 5.5 in steps of
/// 0.01, accumulated as Java's for loop accumulates them.
void expectFiniteAndMonotoneCP(const TubeFinSet& tubeFins, const Rocket& rocket)
{
    double previous = -kInf;
    double mach     = 0.5;
    while (mach <= 5.5)
    {
        const double cp = relativeCP(tubeFins, rocket, mach);
        EXPECT_TRUE(std::isfinite(cp)) << "Tube-fin CP should be finite at mach " << mach;
        EXPECT_GE(cp, previous - 1.0e-12) << "Tube-fin CP should not move forward at mach " << mach;
        previous = cp;
        mach += 0.01;
    }
}

// TubeFinSetCalcTest.testLowAspectRatioTubeFinCPIsFiniteAndMonotone
TEST(TubeFinSetCalc, LowAspectRatioTubeFinCPIsFiniteAndMonotone)
{
    const TestEstesAlphaIII alpha;
    const TubeFinSet&       tubeFins = addTubeFins(alpha, 0.007);

    // AR = 2*innerRadius/chord = 0.2, whose unbounded source equation has a pole near Mach 2.69.
    expectFiniteAndMonotoneCP(tubeFins, *alpha.rocket);

    EXPECT_NEAR(relativeCP(tubeFins, *alpha.rocket, 2.0), 0.25, kEpsilon)
        << "The invalid low-aspect-ratio source branch should not be evaluated";
    EXPECT_GT(relativeCP(tubeFins, *alpha.rocket, 5.2), 0.25)
        << "The tube-fin CP should join the source curve above its validity boundary";
}


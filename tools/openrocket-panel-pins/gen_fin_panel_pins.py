#!/usr/bin/env python3
"""Writes tests/gui/configdialog/FinPanelPins.h from the transcript of FinPanelProbe
(src/probe/FinPanelProbe.java).

usage: gen_fin_panel_pins.py <transcript> <FinPanelPins.h> <OpenRocket commit>

Run by generate.sh (see README.md).

The probe prints sections "== <part> | ..." followed by their lines:
- "panel", "edit", "multi", "multi edit": "== <part> | <source> | <design> | ..." and sorted lines; the pins keep
  the sections per design ("<source>", "<design>") as lines, the section headers without the source and the
  design (as gen_lug_panel_pins.py does);
- "compute": "== compute | <name>" and one line "result=<length> offset=<offset>";
- "dialog": "== dialog | <name>" and its lines in the order printed ("-- <step>" headers, "dialog ...",
  "tree ...", "undo=...", ...). The suffix " bypass=<b> listeners=<n>" of a tree line (Java's config-listener
  state, which QtRocket has not) is left out.
A character outside printable ASCII (the degree sign of the angle unit) is written as a \\u escape.
"""
import pathlib
import re
import subprocess
import sys

LISTENER_STATE = re.compile(r" bypass=(true|false) listeners=\d+$")


def cpp(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= ord(ch) <= 0x7E:
            out.append(ch)
        elif 0xA0 <= ord(ch) <= 0xFFFF:
            out.append(f"\\u{ord(ch):04x}")
        else:
            raise SystemExit(f"unexpected character in {s!r}")
    return '"' + "".join(out) + '"'


def test_name(source: str, design: str) -> str:
    """The design as a test name: letters and digits."""
    if design.endswith(".ork"):
        design = design[: -len(".ork")]
    words = "".join(ch if ch.isalnum() else " " for ch in source + " " + design).split()
    return "".join(w[0].upper() + w[1:] for w in words)


def main() -> None:
    commit = sys.argv[3]
    designs: dict[tuple[str, str], list[str]] = {}
    order: list[tuple[str, str]] = []
    computes: list[tuple[str, str]] = []
    dialogs: list[tuple[str, list[str]]] = []
    current: list[str] | None = None
    compute_name: str | None = None
    with open(sys.argv[1], encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            if line.startswith("== "):
                parts = line[3:].split(" | ")
                part = parts[0]
                compute_name = None
                if part == "compute":
                    compute_name = parts[1]
                    current = None
                elif part == "dialog":
                    dialogs.append((parts[1], []))
                    current = dialogs[-1][1]
                else:
                    source, design = parts[1], parts[2]
                    key = (source, design)
                    if key not in designs:
                        designs[key] = []
                        order.append(key)
                    current = designs[key]
                    current.append("== " + " | ".join([part] + parts[3:]))
            elif compute_name is not None:
                computes.append((compute_name, line))
                compute_name = None
            else:
                if current is None:
                    raise SystemExit(f"a line outside a section: {line!r}")
                current.append(LISTENER_STATE.sub("", line))
    out: list[str] = []
    out.append("#pragma once")
    out.append("")
    out.append("// GENERATED by tools/openrocket-panel-pins/gen_fin_panel_pins.py from FinPanelProbe's output (OpenRocket's TrapezoidFinSetConfig and")
    out.append("// EllipticalFinSetConfig made under Xvfb with SwingPreferences and FlatLaf Light, its")
    out.append("// FinSetConfig.computeFinTabLength() and its ComponentConfigDialog; see fin_panel_golden_tests.cpp);")
    out.append("// do not edit.")
    out.append("")
    out.append("#include <array>")
    out.append("#include <ostream>")
    out.append("#include <span>")
    out.append("#include <string_view>")
    out.append("")
    out.append("namespace QtRocket::Gui::Test")
    out.append("{")
    out.append("")
    out.append("/// The OpenRocket commit the pins come from.")
    out.append(f'inline constexpr std::string_view kFinPanelPinsCommit = "{commit}";')
    out.append("")
    out.append("/// What the probe saw of one design: its sections, each a header line (\"== panel | <index> | <class>\",")
    out.append("/// \"== edit | <index> | <property> <value>\", \"== multi | <index> | <other index> | <class>\", \"== multi")
    out.append("/// edit | <property> <value>\") and the lines that follow it, sorted (see fin_panel_golden_tests.cpp).")
    out.append("struct FinPanelPin")
    out.append("{")
    out.append("    /// \"example\" (a file of data/examples), \"testrocket\" (a TestRockets maker) or \"built\" (a")
    out.append("    /// design of the probe, built in fin_panel_golden_tests.cpp).")
    out.append("    std::string_view                  source;")
    out.append("    std::string_view                  design;")
    out.append("    /// The design as a test name: letters and digits.")
    out.append("    std::string_view                  testName;")
    out.append("    std::span<const std::string_view> lines;")
    out.append("};")
    out.append("")
    out.append("/// What GoogleTest prints for the design of a test that failed.")
    out.append("// NOLINTNEXTLINE(readability-identifier-naming): the name GoogleTest looks for")
    out.append("inline void PrintTo(const FinPanelPin& pin, std::ostream* out)")
    out.append("{")
    out.append("    *out << pin.source << ' ' << pin.design;")
    out.append("}")
    out.append("")
    out.append("/// FinSetConfig.computeFinTabLength() on one of FinSetConfigTest's inputs (and one of the probe's):")
    out.append("/// \"result=<length> offset=<the tab offset given to the model>\", Java's Double.toString().")
    out.append("struct FinTabComputePin")
    out.append("{")
    out.append("    std::string_view name;")
    out.append("    std::string_view line;")
    out.append("};")
    out.append("")
    out.append("/// One run of ComponentConfigDialog with a fin set panel: its steps (\"-- <step>\") and what followed each,")
    out.append("/// in the order printed.")
    out.append("struct FinDialogPin")
    out.append("{")
    out.append("    std::string_view                  name;")
    out.append("    std::span<const std::string_view> lines;")
    out.append("};")
    out.append("")
    out.append("// clang-format off")
    out.append("// NOLINTBEGIN(modernize-raw-string-literal): the lines as the Java probe printed them")
    for n, key in enumerate(order):
        lines = designs[key]
        out.append(f"inline constexpr std::array<std::string_view, {len(lines)}> kFinPanelLines{n}{{")
        for line in lines:
            out.append(f"    {cpp(line)},")
        out.append("};")
    out.append("")
    out.append(f"inline constexpr std::array<FinPanelPin, {len(order)}> kFinPanelPins{{{{")
    for n, (source, design) in enumerate(order):
        out.append(f"    {{.source = {cpp(source)}, .design = {cpp(design)}, .testName = {cpp(test_name(source, design))}, .lines = kFinPanelLines{n}}},")
    out.append("}};")
    out.append("")
    out.append(f"inline constexpr std::array<FinTabComputePin, {len(computes)}> kFinTabComputePins{{{{")
    for name, line in computes:
        out.append(f"    {{.name = {cpp(name)}, .line = {cpp(line)}}},")
    out.append("}};")
    out.append("")
    for n, (name, lines) in enumerate(dialogs):
        out.append(f"inline constexpr std::array<std::string_view, {len(lines)}> kFinDialogLines{n}{{")
        for line in lines:
            out.append(f"    {cpp(line)},")
        out.append("};")
    out.append("")
    out.append(f"inline constexpr std::array<FinDialogPin, {len(dialogs)}> kFinDialogPins{{{{")
    for n, (name, _) in enumerate(dialogs):
        out.append(f"    {{.name = {cpp(name)}, .lines = kFinDialogLines{n}}},")
    out.append("}};")
    out.append("// NOLINTEND(modernize-raw-string-literal)")
    out.append("// clang-format on")
    out.append("")
    out.append("}  // namespace QtRocket::Gui::Test")
    with open(sys.argv[2], "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    # The parts outside "clang-format off" in the repository's style (its .clang-format, wherever the
    # header is written).
    style = pathlib.Path(__file__).resolve().parents[2] / ".clang-format"
    subprocess.run(["clang-format", "-i", f"--style=file:{style}", sys.argv[2]], check=True)


if __name__ == "__main__":
    main()

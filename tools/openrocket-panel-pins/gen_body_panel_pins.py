#!/usr/bin/env python3
"""Writes tests/gui/configdialog/BodyPanelPins.h from the transcript of BodyPanelProbe
(src/probe/BodyPanelProbe.java).

usage: gen_body_panel_pins.py <transcript> <BodyPanelPins.h> <OpenRocket commit>

Run by generate.sh (see README.md).

The probe prints sections "== <part> | <source> | <design> | <index> [| <other>] | <class>" followed by
sorted lines; the pins keep the sections per design ("<source>", "<design>") as lines, the section
headers without the source and the design.
"""
import pathlib
import subprocess
import sys

def cpp(s: str) -> str:
    for ch in s:
        if ord(ch) > 0x7E or ord(ch) < 0x20:
            raise SystemExit(f"not printable ASCII: {s!r}")
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def test_name(source: str, design: str) -> str:
    """The design as a test name: letters and digits."""
    if design.endswith(".ork"):
        design = design[: -len(".ork")]
    words = "".join(ch if ch.isalnum() else " " for ch in source + " " + design).split()
    return "".join(w[0].upper() + w[1:] for w in words)


def main() -> None:
    commit = sys.argv[3]
    designs: dict[tuple[str, str], list[str]] = {}
    order: list[tuple[str, str]] = []
    current: list[str] | None = None
    with open(sys.argv[1], encoding="ascii") as f:
        for raw in f:
            line = raw.rstrip("\n")
            if line.startswith("== "):
                parts = line[3:].split(" | ")
                part, source, design = parts[0], parts[1], parts[2]
                key = (source, design)
                if key not in designs:
                    designs[key] = []
                    order.append(key)
                current = designs[key]
                current.append("== " + " | ".join([part] + parts[3:]))
            else:
                if current is None:
                    raise SystemExit("a line before the first section")
                current.append(line)
    out: list[str] = []
    out.append("#pragma once")
    out.append("")
    out.append("// GENERATED by tools/openrocket-panel-pins/gen_body_panel_pins.py from BodyPanelProbe's output (OpenRocket's BodyTubeConfig,")
    out.append("// NoseConeConfig and TransitionConfig made under Xvfb with SwingPreferences and FlatLaf Light; see")
    out.append("// BodyPanelGolden in body_panel_golden_tests.cpp); do not edit.")
    out.append("")
    out.append("#include <array>")
    out.append("#include <ostream>")
    out.append("#include <span>")
    out.append("#include <string_view>")
    out.append("")
    out.append("namespace QtRocket::Gui::Test")
    out.append("{")
    out.append("")
    out.append("/// The OpenRocket commit the pins come from.")
    out.append(f'inline constexpr std::string_view kBodyPanelPinsCommit = "{commit}";')
    out.append("")
    out.append("/// What the probe saw of one design: its sections, each a header line \"== <part> | <index> [|")
    out.append("/// <other index>] | <class>\" and the lines that follow it, sorted (see body_panel_golden_tests.cpp).")
    out.append("struct BodyPanelPin")
    out.append("{")
    out.append("    /// \"example\" (a file of data/examples), \"testrocket\" (a TestRockets maker) or \"built\" (a")
    out.append("    /// design of the probe, built in body_panel_golden_tests.cpp).")
    out.append("    std::string_view                  source;")
    out.append("    std::string_view                  design;")
    out.append("    /// The design as a test name: letters and digits.")
    out.append("    std::string_view                  testName;")
    out.append("    std::span<const std::string_view> lines;")
    out.append("};")
    out.append("")
    out.append("/// What GoogleTest prints for the design of a test that failed.")
    out.append("// NOLINTNEXTLINE(readability-identifier-naming): the name GoogleTest looks for")
    out.append("inline void PrintTo(const BodyPanelPin& pin, std::ostream* out)")
    out.append("{")
    out.append("    *out << pin.source << ' ' << pin.design;")
    out.append("}")
    out.append("")
    out.append("// clang-format off")
    out.append("// NOLINTBEGIN(modernize-raw-string-literal): the lines as the Java probe printed them")
    for n, key in enumerate(order):
        lines = designs[key]
        out.append(f"inline constexpr std::array<std::string_view, {len(lines)}> kBodyPanelLines{n}{{")
        for line in lines:
            out.append(f"    {cpp(line)},")
        out.append("};")
    out.append("")
    out.append(f"inline constexpr std::array<BodyPanelPin, {len(order)}> kBodyPanelPins{{{{")
    for n, (source, design) in enumerate(order):
        out.append(f"    {{.source = {cpp(source)}, .design = {cpp(design)}, .testName = {cpp(test_name(source, design))}, .lines = kBodyPanelLines{n}}},")
    out.append("}};")
    out.append("// NOLINTEND(modernize-raw-string-literal)")
    out.append("// clang-format on")
    out.append("")
    out.append("}  // namespace QtRocket::Gui::Test")
    with open(sys.argv[2], "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    # The parts outside "clang-format off" in the repository's style (its .clang-format, wherever the
    # header is written).
    style = pathlib.Path(__file__).resolve().parents[2] / ".clang-format"
    subprocess.run(["clang-format", "-i", f"--style=file:{style}", sys.argv[2]], check=True)


if __name__ == "__main__":
    main()

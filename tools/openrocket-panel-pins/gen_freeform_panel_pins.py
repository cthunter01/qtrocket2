#!/usr/bin/env python3
"""Writes tests/gui/configdialog/FreeformPanelPins.h from the transcript of FreeformPanelProbe
(src/probe/FreeformPanelProbe.java).

usage: gen_freeform_panel_pins.py <transcript> <FreeformPanelPins.h> <OpenRocket commit>

Run by generate.sh (see README.md).

The probe prints sections "== <part> | <source> | <design> | ..." ("panel", "edit", "multi", "multi edit")
followed by their lines; the pins keep the sections per design ("<source>", "<design>"), the section headers
without the source and the design (as gen_fin_panel_pins.py does). Two kinds of line change on the way:
- the four arrow buttons of the point table's scroll bars ('shape button "" enabled=true focusable=false
  tip=null', Swing's BasicArrowButtons) are left out;
- a label's 'size=<s> base=<b>' (its font size and the default label's) becomes 'relative=<s - b>'.
A character outside printable ASCII (the degree sign, the ellipsis, the triangle) is written as a \\u escape.
"""
import pathlib
import re
import subprocess
import sys

ARROW_BUTTON = 'shape button "" enabled=true focusable=false tip=null'
LABEL_SIZE = re.compile(r" size=([0-9.]+) base=([0-9.]+)$")


def cpp(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= ord(ch) <= 0x7E:
            out.append(ch)
        elif 0xA0 <= ord(ch) <= 0xFFFF:
            out.append(f"\\u{ord(ch):04x}")
        else:
            raise SystemExit(f"unexpected character in {s!r}")
    return '"' + "".join(out) + '"'


def test_name(source: str, design: str) -> str:
    """The design as a test name: letters and digits."""
    if design.endswith(".ork"):
        design = design[: -len(".ork")]
    words = "".join(ch if ch.isalnum() else " " for ch in source + " " + design).split()
    return "".join(w[0].upper() + w[1:] for w in words)


def relative_size(match: re.Match) -> str:
    return f" relative={float(match.group(1)) - float(match.group(2))}"


def main() -> None:
    commit = sys.argv[3]
    designs: dict[tuple[str, str], list[str]] = {}
    order: list[tuple[str, str]] = []
    current: list[str] | None = None
    with open(sys.argv[1], encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            if line.startswith("== "):
                parts = line[3:].split(" | ")
                part, source, design = parts[0], parts[1], parts[2]
                key = (source, design)
                if key not in designs:
                    designs[key] = []
                    order.append(key)
                current = designs[key]
                current.append("== " + " | ".join([part] + parts[3:]))
            else:
                if current is None:
                    raise SystemExit(f"a line outside a section: {line!r}")
                if line == ARROW_BUTTON:
                    continue
                current.append(LABEL_SIZE.sub(relative_size, line))
    out: list[str] = []
    out.append("#pragma once")
    out.append("")
    out.append("// GENERATED by tools/openrocket-panel-pins/gen_freeform_panel_pins.py from FreeformPanelProbe's output (OpenRocket's FreeformFinSetConfig with")
    out.append("// its FinPointFigure and FinPointScrollPane made under Xvfb with SwingPreferences and FlatLaf Light; see")
    out.append("// freeform_panel_golden_tests.cpp); do not edit.")
    out.append("")
    out.append("#include <array>")
    out.append("#include <ostream>")
    out.append("#include <span>")
    out.append("#include <string_view>")
    out.append("")
    out.append("namespace QtRocket::Gui::Test")
    out.append("{")
    out.append("")
    out.append("/// The OpenRocket commit the pins come from.")
    out.append(f'inline constexpr std::string_view kFreeformPanelPinsCommit = "{commit}";')
    out.append("")
    out.append("/// What the probe saw of one design: its sections, each a header line (\"== panel | <index> | <class>\",")
    out.append("/// \"== edit | <step>\", \"== multi | <index> | <other index> | <class>\", \"== multi edit | <step>\") and the")
    out.append("/// lines that follow it: a panel's sorted, a step's in the order printed (see")
    out.append("/// freeform_panel_golden_tests.cpp).")
    out.append("struct FreeformPanelPin")
    out.append("{")
    out.append("    /// \"example\" (a file of data/examples), \"testrocket\" (a TestRockets maker) or \"built\" (a")
    out.append("    /// design of the probe, built in freeform_panel_golden_tests.cpp).")
    out.append("    std::string_view                  source;")
    out.append("    std::string_view                  design;")
    out.append("    /// The design as a test name: letters and digits.")
    out.append("    std::string_view                  testName;")
    out.append("    std::span<const std::string_view> lines;")
    out.append("};")
    out.append("")
    out.append("/// What GoogleTest prints for the design of a test that failed.")
    out.append("// NOLINTNEXTLINE(readability-identifier-naming): the name GoogleTest looks for")
    out.append("inline void PrintTo(const FreeformPanelPin& pin, std::ostream* out)")
    out.append("{")
    out.append("    *out << pin.source << ' ' << pin.design;")
    out.append("}")
    out.append("")
    out.append("// clang-format off")
    out.append("// NOLINTBEGIN(modernize-raw-string-literal): the lines as the Java probe printed them")
    for n, key in enumerate(order):
        lines = designs[key]
        out.append(f"inline constexpr std::array<std::string_view, {len(lines)}> kFreeformPanelLines{n}{{")
        for line in lines:
            out.append(f"    {cpp(line)},")
        out.append("};")
    out.append("")
    out.append(f"inline constexpr std::array<FreeformPanelPin, {len(order)}> kFreeformPanelPins{{{{")
    for n, (source, design) in enumerate(order):
        out.append(f"    {{.source = {cpp(source)}, .design = {cpp(design)}, .testName = {cpp(test_name(source, design))}, .lines = kFreeformPanelLines{n}}},")
    out.append("}};")
    out.append("// NOLINTEND(modernize-raw-string-literal)")
    out.append("// clang-format on")
    out.append("")
    out.append("}  // namespace QtRocket::Gui::Test")
    with open(sys.argv[2], "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    # The parts outside "clang-format off" in the repository's style (its .clang-format, wherever the
    # header is written).
    style = pathlib.Path(__file__).resolve().parents[2] / ".clang-format"
    subprocess.run(["clang-format", "-i", f"--style=file:{style}", sys.argv[2]], check=True)


if __name__ == "__main__":
    main()

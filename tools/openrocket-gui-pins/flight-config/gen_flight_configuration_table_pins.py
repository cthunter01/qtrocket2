#!/usr/bin/env python3
"""Writes tests/gui/flightconfig/FlightConfigurationTablePins.h from FlightConfigurationTablesProbe's output.

usage: gen_flight_configuration_table_pins.py PROBE_OUTPUT HEADER COMMIT

PROBE_OUTPUT is the probe's standard output (generate.sh sends OpenRocket's log to standard error): one line
each, its fields separated by tabs (see the probe's class comment). A style the QtRocket tables do not know
(anything but plain in UITheme's TEXT and italic in TEXT_DIM, or a shaded motor text, column 0 or mount row)
stops the generator: decide what the table should show first.
"""
import os
import pathlib
import subprocess
import sys

HEADER_TOP = """#pragma once

// GENERATED by tools/openrocket-gui-pins/generate.sh
// (flight-config/gen_flight_configuration_table_pins.py from the output of
// flight-config/probe/FlightConfigurationTablesProbe.java: the tables of OpenRocket's "Motors &
// Configuration" tab, its own table models and cell renderers, headless with SwingPreferences and
// FlatLaf Light; see flight_configuration_tables_golden_tests.cpp); do not edit.

#include <array>
#include <ostream>
#include <span>
#include <string_view>

namespace QtRocket::Gui::Test
{{

/// The OpenRocket commit the pins come from.
inline constexpr std::string_view kFlightConfigurationTablePinsCommit = "{commit}";

/// UITheme's TEXT and TEXT_DIM in FlatLaf Light, as 0xRRGGBB: the colours of the two styles.
inline constexpr unsigned kJavaTextColour    = {text};
inline constexpr unsigned kJavaDimTextColour = {dim};

/// How OpenRocket's renderer styled a text (FlightConfigurableCellRenderer's regular() and
/// shaded()): REGULAR plain in TEXT, SHADED italic in TEXT_DIM.
enum class CellStylePin
{{
    REGULAR,
    SHADED,
}};

/// A row of the tables: a flight configuration of the rocket (getIds() order; never the default).
struct ConfigurationRowPin
{{
    /// The id's key (FlightConfigurationId.key).
    std::string_view key;
    /// Whether the maker of a test rocket draws the id (another seed gave another one): compare by
    /// row.
    bool drawn;
    /// getNameRaw() and isNameOverridden().
    std::string_view rawName;
    bool             nameOverridden;
    /// Column 0 as the renderer shows it (RocketDescriptor.format(rocket, id), always REGULAR).
    std::string_view name;
}};

/// A motor cell (MotorTableCellRenderer: two labels): the motor, always REGULAR ("None", or the
/// name with its delay, after "<n>", U+00D7 and a space for a cluster), and the ignition ("<event>"
/// or "<event> + <delay>", inside "Default (...)" and SHADED when the configuration has no ignition
/// override); hasIgnitionOverride() of the cell's configuration (mount.getMotorConfig(id), the
/// mount's default when its set has no entry for the id) and whether the set has one
/// (containsId()).
struct MotorCellPin
{{
    int              row;
    int              column;
    std::string_view motor;
    std::string_view ignition;
    CellStylePin     ignitionStyle;
    bool             ignitionOverride;
    bool             containsId;
}};

/// A recovery or stage cell (RecoveryTableCellRenderer, SeparationTableCellRenderer): its text and
/// style (SHADED iff the set's isDefault(id), OpenRocket bug 1: never, an id without an override is
/// no default to it), isDefault(id) and containsId(id).
struct ValueCellPin
{{
    int              row;
    int              column;
    std::string_view text;
    CellStylePin     style;
    bool             isDefault;
    bool             containsId;
}};

/// A row of MotorMountTableModel: every MotorMount of the rocket, in its order.
struct MotorMountRowPin
{{
    bool             motorMount;
    std::string_view name;
}};

/// Column 0 of the last row after setName(raw) (the raw name put back after each).
struct NamePin
{{
    std::string_view raw;
    std::string_view text;
}};

/// One design's tables: the motor table (column 0 and the acting motor mounts), the recovery table
/// (every RecoveryDevice) and the stage table (the AxialStages of stage number > 0), each header
/// with column 0 ("Configuration"), their cells in row order, and the motor-mount table.
struct FlightConfigurationTablesPin
{{
    /// The scenario's name in the probe: "<source>:<design>".
    std::string_view name;
    /// The scenario as a test name: letters and digits.
    std::string_view testName;
    /// "example" (a file of data/examples) or "testrocket" (a TestRockets maker).
    std::string_view source;
    std::string_view design;
    /// The row of the rocket's selected configuration (-1: the default) and getStageCount().
    int                                    selectedRow;
    int                                    stageCount;
    std::span<const ConfigurationRowPin>   configurations;
    std::span<const std::string_view>      motorHeaders;
    std::span<const MotorCellPin>          motorCells;
    std::span<const std::string_view>      recoveryHeaders;
    std::span<const ValueCellPin>          recoveryCells;
    std::span<const std::string_view>      stageHeaders;
    std::span<const ValueCellPin>          stageCells;
    std::span<const MotorMountRowPin>      motorMounts;
    std::span<const NamePin>               names;
}};

/// What GoogleTest prints for the scenario of a test that failed: its name.
// NOLINTNEXTLINE(readability-identifier-naming): the name GoogleTest looks for
inline void PrintTo(const FlightConfigurationTablesPin& pin, std::ostream* out)
{{
    *out << pin.name;
}}

// clang-format off
// NOLINTBEGIN(modernize-use-designated-initializers): tables printed by the Java probe
// NOLINTBEGIN(modernize-raw-string-literal): the texts escaped alike, quotes and UTF-8 bytes
"""

HEADER_BOTTOM = """// NOLINTEND(modernize-raw-string-literal)
// NOLINTEND(modernize-use-designated-initializers)
// clang-format on

}  // namespace QtRocket::Gui::Test
"""

STYLES = {"plain/text": "CellStylePin::REGULAR", "italic/dim": "CellStylePin::SHADED"}


def cpp_string(text):
    out = ['"']
    for ch in text:
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= ord(ch) < 0x7F:
            if out[-1].startswith("\\x") and ch in "0123456789abcdefABCDEF":
                # A hex digit after an escape would continue it.
                out.append('" "')
            out.append(ch)
        else:
            # UTF-8 bytes as escapes (the core's texts are UTF-8 std::string).
            for byte in ch.encode("utf-8"):
                out.append("\\x%02X" % byte)
    out.append('"')
    return "".join(out)


def ident(name):
    words = []
    word = ""
    for ch in name:
        if ch.isalnum():
            word += ch
        else:
            if word:
                words.append(word)
            word = ""
    if word:
        words.append(word)
    return "".join(w[0].upper() + w[1:] for w in words)


def boolean(text):
    return {"true": "true", "false": "false"}[text]


def style(text, line, regular_only=False):
    if text not in STYLES or (regular_only and text != "plain/text"):
        raise SystemExit("unexpected style %s: %s" % (text, line))
    return STYLES[text]


def colour(text, line):
    if len(text) != 7 or text[0] != "#":
        raise SystemExit("unexpected colour %s: %s" % (text, line))
    return "0x" + text[1:].upper()


def expect_fields(fields, count, line):
    if len(fields) != count:
        raise SystemExit("expected %d fields: %r" % (count, line))


# The rows of the structs of HEADER_TOP, written positionally (the header's tables suppress
# modernize-use-designated-initializers): these functions are the one place that knows the order of their
# fields. open-designs/gen_open_designs_tab_pins.py writes its rows of these structs (OpenDesignsTabPins.h
# includes this family's header) through them too, so a change of a struct's fields is a change of both
# generators' output: regenerate both families (generate.sh flight-config open-designs).


def configuration(fields, line):
    """The row of a C line (index, key, drawn, raw name, overridden); its column 0 comes with its M0 line."""
    expect_fields(fields, 6, line)
    return {"key": fields[2], "drawn": boolean(fields[3]), "raw": fields[4], "overridden": boolean(fields[5])}


def configuration_row(row, scenario):
    """A ConfigurationRowPin of @p row (configuration(), with the column 0 of its M0 line) of @p scenario."""
    if "name" not in row:
        raise SystemExit("no column 0 for a row of " + scenario)
    return "    {%s, %s, %s, %s, %s}," % (cpp_string(row["key"]), row["drawn"], cpp_string(row["raw"]),
                                         row["overridden"], cpp_string(row["name"]))


def motor_cell_row(fields, line):
    """A MotorCellPin of an M line (row, column, motor, motor style, ignition, ignition style, override,
    containsId)."""
    expect_fields(fields, 9, line)
    style(fields[4], line, regular_only=True)
    return "    {%d, %d, %s, %s, %s, %s, %s}," % (
        int(fields[1]), int(fields[2]), cpp_string(fields[3]), cpp_string(fields[5]), style(fields[6], line),
        boolean(fields[7]), boolean(fields[8]))


def value_cell_row(fields, line):
    """A ValueCellPin of an R or T line (row, column, text, style, isDefault, containsId)."""
    expect_fields(fields, 7, line)
    return "    {%d, %d, %s, %s, %s, %s}," % (
        int(fields[1]), int(fields[2]), cpp_string(fields[3]), style(fields[4], line), boolean(fields[5]),
        boolean(fields[6]))


def motor_mount_row(fields, line):
    """A MotorMountRowPin of a P line (index, isMotorMount, name)."""
    expect_fields(fields, 4, line)
    return "    {%s, %s}," % (boolean(fields[2]), cpp_string(fields[3]))


def parse(lines):
    colours = None
    scenarios = []
    current = None
    for line in lines:
        line = line.rstrip("\n")
        fields = line.split("\t")
        tag = fields[0]
        if tag == "COLORS":
            expect_fields(fields, 3, line)
            colours = (colour(fields[1], line), colour(fields[2], line))
        elif tag == "D":
            expect_fields(fields, 2, line)
            current = {"name": fields[1], "configurations": [], "motorHeaders": [], "motorCells": [],
                       "recoveryHeaders": [], "recoveryCells": [], "stageHeaders": [], "stageCells": [],
                       "mounts": [], "names": []}
            scenarios.append(current)
        elif tag == "S":
            expect_fields(fields, 3, line)
            current["selected"] = int(fields[1])
            current["stages"] = int(fields[2])
        elif tag == "C":
            row = configuration(fields, line)
            if int(fields[1]) != len(current["configurations"]):
                raise SystemExit("rows out of order: " + line)
            current["configurations"].append(row)
        elif tag in ("MH", "RH", "TH"):
            expect_fields(fields, 3, line)
            headers = current[{"MH": "motorHeaders", "RH": "recoveryHeaders", "TH": "stageHeaders"}[tag]]
            if int(fields[1]) != len(headers):
                raise SystemExit("columns out of order: " + line)
            headers.append(fields[2])
        elif tag == "M0":
            expect_fields(fields, 4, line)
            row = int(fields[1])
            style(fields[3], line, regular_only=True)
            current["configurations"][row]["name"] = fields[2]
        elif tag == "M":
            current["motorCells"].append(motor_cell_row(fields, line))
        elif tag in ("R", "T"):
            current["recoveryCells" if tag == "R" else "stageCells"].append(value_cell_row(fields, line))
        elif tag == "P":
            row = motor_mount_row(fields, line)
            if int(fields[1]) != len(current["mounts"]):
                raise SystemExit("mount rows out of order: " + line)
            current["mounts"].append(row)
        elif tag == "N":
            expect_fields(fields, 3, line)
            current["names"].append("    {%s, %s}," % (cpp_string(fields[1]), cpp_string(fields[2])))
        else:
            raise SystemExit("unexpected line: " + line)
    if colours is None:
        raise SystemExit("no COLORS line")
    return colours, scenarios


def array(out, element, name, rows):
    """Appends the table @p name of @p rows (each a line of the header)."""
    if not rows:
        out.append("inline constexpr std::array<%s, 0> %s{};" % (element, name))
        return
    out.append("inline constexpr std::array<%s, %d> %s{{" % (element, len(rows), name))
    out.extend(rows)
    out.append("}};")


def main():
    probe, header, commit = sys.argv[1:4]
    with open(probe, encoding="utf-8") as f:
        (text, dim), scenarios = parse(f.readlines())

    out = [HEADER_TOP.format(commit=commit, text=text, dim=dim)]
    table = []
    for scenario in scenarios:
        name = ident(scenario["name"])
        source, design = scenario["name"].split(":", 1)
        rows = [configuration_row(row, scenario["name"]) for row in scenario["configurations"]]
        names = {}
        for part, element, key in (("Configurations", "ConfigurationRowPin", None),
                                   ("MotorHeaders", "std::string_view", "motorHeaders"),
                                   ("MotorCells", "MotorCellPin", "motorCells"),
                                   ("RecoveryHeaders", "std::string_view", "recoveryHeaders"),
                                   ("RecoveryCells", "ValueCellPin", "recoveryCells"),
                                   ("StageHeaders", "std::string_view", "stageHeaders"),
                                   ("StageCells", "ValueCellPin", "stageCells"),
                                   ("MotorMounts", "MotorMountRowPin", "mounts"),
                                   ("Names", "NamePin", "names")):
            names[part] = "k" + part + name
            if key is None:
                lines = rows
            elif key.endswith("Headers"):
                lines = ["    %s," % cpp_string(header_text) for header_text in scenario[key]]
            else:
                lines = scenario[key]
            array(out, element, names[part], lines)
        table.append("    {%s, %s, %s, %s, %d, %d, %s}," % (
            cpp_string(scenario["name"]), cpp_string(name), cpp_string(source), cpp_string(design),
            scenario["selected"], scenario["stages"],
            ", ".join(names[part] for part in ("Configurations", "MotorHeaders", "MotorCells", "RecoveryHeaders",
                                               "RecoveryCells", "StageHeaders", "StageCells", "MotorMounts",
                                               "Names"))))
    array(out, "FlightConfigurationTablesPin", "kFlightConfigurationTables", table)
    out.append(HEADER_BOTTOM)
    with open(header, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    # The repository's style (its .clang-format, wherever the header is written: generate.sh --check
    # writes it into a temporary directory), so that a run reproduces the committed header byte for byte.
    style_file = pathlib.Path(__file__).resolve().parents[3] / ".clang-format"
    clang_format = os.environ.get("CLANG_FORMAT", "clang-format")
    subprocess.run([clang_format, "-i", f"--style=file:{style_file}", header], check=True)


if __name__ == "__main__":
    main()

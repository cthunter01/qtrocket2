#!/usr/bin/env python3
"""Writes tests/gui/flightconfig/FlightConfigurationOperationPins.h from FlightConfigurationOperationsProbe's output.

usage: gen_flight_configuration_operation_pins.py PROBE_OUTPUT HEADER COMMIT

PROBE_OUTPUT is the probe's standard output (generate.sh sends OpenRocket's log to the probe's log): one line
each, its fields separated by tabs (see the probe's class comment). Each step becomes the lines the test
compares: its action, the cells it acts on, the dialogs' first states and answers, its change events, and the
state after it, whole lines as the probe printed them. Two things change on the way:
- the events: OpenRocket's FlightConfigurationPanel.configurationChanged() fires each of its events once per
  sub-panel (three in a row, origin "panel"), where QtRocket fires one (FlightConfigurationEditing); each such
  run of three becomes one event. An event is kept as "EVENT", its type and its source's name (the class and
  the origin go);
- the dialogs' first states (Q): the configuration's name is taken out of the "Override for the {0} flight
  configuration only" radio button, which QtRocket's request carries alone.
A line of another kind, or an event run that is not a multiple of three, stops the generator.
"""
import os
import pathlib
import subprocess
import sys

HEADER_TOP = """#pragma once

// GENERATED by tools/openrocket-gui-pins/generate.sh
// (flight-config/gen_flight_configuration_operation_pins.py from the output of
// flight-config/probe/FlightConfigurationOperationsProbe.java: the operations of OpenRocket's "Motors &
// Configuration" tab, run by its own FlightConfigurationPanel under xvfb with SwingPreferences and FlatLaf
// Light, with the undo positions of QtRocket's fix of bug 5; see
// flight_configuration_operations_golden_tests.cpp); do not edit.

#include <array>
#include <ostream>
#include <span>
#include <string_view>

namespace QtRocket::Gui::Test
{{

/// The OpenRocket commit the pins come from.
inline constexpr std::string_view kFlightConfigurationOperationPinsCommit = "{commit}";

/// One step of a scenario: what the probe did and what OpenRocket showed afterwards, each a line of
/// the probe's transcript (its fields separated by tabs; FlightConfigurationOperationsProbe's class
/// comment says what each kind of line holds).
struct OperationStepPin
{{
    /// "STEP", the step's number and its kind and arguments: OPEN, SELECT tab row0 col0 row1 col1, TAB
    /// tab, UNDO, REDO, EDIT what, MOUNT row value, and the operations with their answers.
    std::string_view action;
    /// "CELLS" tab rows cols: the cells an operation acts on (the configurations' rows and the
    /// components' columns of the tab's table, comma-separated); empty for a step without.
    std::string_view cells;
    /// The dialogs as they opened ("Q", the kind, the configuration's name for the value dialogs, ...),
    /// in order.
    std::span<const std::string_view> questions;
    /// The dialogs' answers ("A", the kind, ok or cancel, ...), in order.
    std::span<const std::string_view> answers;
    /// The rocket's change events during the step: "EVENT", the type and the source's name (one for
    /// each event of FlightConfigurationPanel.configurationChanged(), which OpenRocket fires once per
    /// sub-panel).
    std::span<const std::string_view> events;
    /// The state after the step: SEL, CONF, SIM, MOUNT and ME, DEV and DE, STG and SE, the three tables
    /// (MH and MT, RH and RT, TH and TT) and UNDO, in the probe's order.
    std::span<const std::string_view> state;
}};

/// A scenario: a design (an example, or a new one) and its steps, the first one OPEN.
struct OperationScenarioPin
{{
    std::string_view                  name;
    /// "example:<file of data/examples>" or "new".
    std::string_view                  source;
    std::span<const OperationStepPin> steps;
}};

/// What GoogleTest prints for the scenario of a test that failed: its name.
// NOLINTNEXTLINE(readability-identifier-naming): the name GoogleTest looks for
inline void PrintTo(const OperationScenarioPin& pin, std::ostream* out)
{{
    *out << pin.name;
}}

// clang-format off
// NOLINTBEGIN(modernize-use-designated-initializers): tables printed by the Java probe
// NOLINTBEGIN(modernize-raw-string-literal): the texts escaped alike, quotes, tabs and UTF-8 bytes
"""

HEADER_BOTTOM = """// NOLINTEND(modernize-raw-string-literal)
// NOLINTEND(modernize-use-designated-initializers)
// clang-format on

}  // namespace QtRocket::Gui::Test
"""

STATE_TAGS = {"SEL", "CONF", "SIM", "MOUNT", "ME", "DEV", "DE", "STG", "SE", "MH", "MT", "RH", "RT", "TH", "TT",
              "UNDO"}
OVERRIDE_PREFIX = "Override for the "
OVERRIDE_SUFFIX = " flight configuration only"


def cpp_string(text):
    out = ['"']
    for ch in text:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ch == "\t":
            out.append("\\t")
        elif 0x20 <= ord(ch) < 0x7F:
            if out[-1].startswith("\\x") and ch in "0123456789abcdefABCDEF":
                # A hex digit after an escape would continue it.
                out.append('" "')
            out.append(ch)
        else:
            # UTF-8 bytes as escapes (the core's texts are UTF-8 std::string).
            for byte in ch.encode("utf-8"):
                out.append("\\x%02X" % byte)
    out.append('"')
    return "".join(out)


def ident(name):
    words = []
    word = ""
    for ch in name:
        if ch.isalnum():
            word += ch
        else:
            if word:
                words.append(word)
            word = ""
    if word:
        words.append(word)
    return "".join(w[0].upper() + w[1:] for w in words)


def question(fields, line):
    """A Q line, the value dialogs' override text replaced by the configuration's name."""
    if fields[1] in ("IGNITION", "DEPLOYMENT", "SEPARATION"):
        text = fields[2]
        if not text.startswith(OVERRIDE_PREFIX) or not text.endswith(OVERRIDE_SUFFIX):
            raise SystemExit("unexpected override text: " + line)
        fields = fields[:2] + [text[len(OVERRIDE_PREFIX):len(text) - len(OVERRIDE_SUFFIX)]] + fields[3:]
    return "\t".join(fields)


def collapse(events, where):
    """The step's events, each run of three identical "panel" events as one; origin and class dropped."""
    out = []
    i = 0
    while i < len(events):
        fields = events[i]
        if fields[4] == "panel":
            j = i
            while j < len(events) and events[j][4] == "panel" and events[j][1:4] == fields[1:4]:
                j += 1
            run = j - i
            if run % 3 != 0:
                raise SystemExit("a run of %d panel events in %s" % (run, where))
            out.extend(["\t".join(["EVENT", fields[1], fields[3]])] * (run // 3))
            i = j
        else:
            out.append("\t".join(["EVENT", fields[1], fields[3]]))
            i += 1
    return out


def parse(lines):
    scenarios = []
    scenario = None
    step = None
    for line in lines:
        line = line.rstrip("\n")
        fields = line.split("\t")
        tag = fields[0]
        if tag == "D":
            if len(fields) != 3:
                raise SystemExit("unexpected D line: " + line)
            scenario = {"name": fields[1], "source": fields[2], "steps": []}
            scenarios.append(scenario)
        elif tag == "STEP":
            if step is not None:
                raise SystemExit("a STEP without END: " + line)
            if int(fields[1]) != len(scenario["steps"]) + 1:
                raise SystemExit("steps out of order: " + line)
            step = {"action": line, "cells": "", "questions": [], "answers": [], "events": [], "state": []}
        elif tag == "CELLS":
            if step["cells"]:
                raise SystemExit("two CELLS lines in a step: " + line)
            step["cells"] = line
        elif tag == "Q":
            step["questions"].append(question(fields, line))
        elif tag == "A":
            step["answers"].append(line)
        elif tag == "EVENT":
            if len(fields) != 5:
                raise SystemExit("unexpected EVENT line: " + line)
            step["events"].append(fields)
        elif tag in STATE_TAGS:
            step["state"].append(line)
        elif tag == "END":
            step["events"] = collapse(step["events"], "%s step %d" % (scenario["name"], len(scenario["steps"]) + 1))
            scenario["steps"].append(step)
            step = None
        else:
            raise SystemExit("unexpected line: " + line)
    if step is not None:
        raise SystemExit("the transcript ends inside a step")
    return scenarios


def array(out, element, name, rows):
    """Appends the table @p name of @p rows (each a line of the header)."""
    if not rows:
        out.append("inline constexpr std::array<%s, 0> %s{};" % (element, name))
        return
    out.append("inline constexpr std::array<%s, %d> %s{{" % (element, len(rows), name))
    out.extend(rows)
    out.append("}};")


def main():
    probe, header, commit = sys.argv[1:4]
    with open(probe, encoding="utf-8") as f:
        scenarios = parse(f.readlines())

    out = [HEADER_TOP.format(commit=commit)]
    table = []
    for scenario in scenarios:
        name = ident(scenario["name"])
        steps = []
        for number, step in enumerate(scenario["steps"], start=1):
            prefix = "k%sStep%d" % (name, number)
            for part in ("questions", "answers", "events", "state"):
                array(out, "std::string_view", prefix + part[0].upper() + part[1:],
                      ["    %s," % cpp_string(text) for text in step[part]])
            steps.append("    {%s, %s, %sQuestions, %sAnswers, %sEvents, %sState}," % (
                cpp_string(step["action"]), cpp_string(step["cells"]), prefix, prefix, prefix, prefix))
        array(out, "OperationStepPin", "k%sSteps" % name, steps)
        table.append("    {%s, %s, k%sSteps}," % (cpp_string(scenario["name"]), cpp_string(scenario["source"]),
                                                  name))
    array(out, "OperationScenarioPin", "kFlightConfigurationOperations", table)
    out.append(HEADER_BOTTOM)
    with open(header, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    # The repository's style (its .clang-format, wherever the header is written: generate.sh --check
    # writes it into a temporary directory), so that a run reproduces the committed header byte for byte.
    style_file = pathlib.Path(__file__).resolve().parents[3] / ".clang-format"
    clang_format = os.environ.get("CLANG_FORMAT", "clang-format")
    subprocess.run([clang_format, "-i", f"--style=file:{style_file}", header], check=True)


if __name__ == "__main__":
    main()

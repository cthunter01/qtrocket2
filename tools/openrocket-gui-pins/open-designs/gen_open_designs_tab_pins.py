#!/usr/bin/env python3
"""Writes tests/gui/exit/OpenDesignsTabPins.h from OpenDesignsTabProbe's output.

usage: gen_open_designs_tab_pins.py PROBE_OUTPUT HEADER COMMIT

PROBE_OUTPUT is the probe's standard output (generate.sh sends OpenRocket's log to standard error): one line
each, its fields separated by tabs (see the probe's class comment). The header reuses the cell types of the
flight-config family's FlightConfigurationTablePins.h, and this generator that family's helpers: its rows of
those types come from that generator's row functions (configuration_row(), motor_cell_row(), value_cell_row(),
motor_mount_row(): the one place that knows their fields' order, so a change there is regenerated into both
headers by generate.sh flight-config open-designs), a style the QtRocket tables do not know stops it, as there,
and so does a tab whose opening changed the design.
"""
import os
import pathlib
import subprocess
import sys

# The flight-config family's generator, imported without leaving a __pycache__ in the repository.
sys.dont_write_bytecode = True
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "flight-config"))
import gen_flight_configuration_table_pins as tables  # noqa: E402

HEADER_TOP = """#pragma once

// GENERATED by tools/openrocket-gui-pins/generate.sh
// (open-designs/gen_open_designs_tab_pins.py from the output of
// open-designs/probe/OpenDesignsTabProbe.java: OpenRocket's "Motors & Configuration" tab as it
// opens for each design of OpenDesignsExitGolden, its real FlightConfigurationPanel with
// SwingPreferences and FlatLaf Light; see open_designs_exit_tests.cpp,
// TheConfigurationTabShowsOpenRocketsTables); do not edit.

#include <array>
#include <span>
#include <string_view>

#include "flightconfig/FlightConfigurationTablePins.h"

namespace QtRocket::Gui::Test
{{

/// The OpenRocket commit the pins come from.
inline constexpr std::string_view kOpenDesignsTabPinsCommit = "{commit}";

/// UITheme's TEXT and TEXT_DIM in FlatLaf Light, as 0xRRGGBB, as the probe saw them (the colours of
/// CellStylePin's two styles).
inline constexpr unsigned kOpenDesignsTabTextColour    = {text};
inline constexpr unsigned kOpenDesignsTabDimTextColour = {dim};

/// A sub-tab or a button of the tab and whether it is enabled: a sub-tab by its title, a button by
/// "<panel>.<field>", the Java field that holds it in FlightConfigurationPanel ("tab") or in the
/// sub-panel ("motors", "recovery", "stages").
struct EnabledPin
{{
    std::string_view name;
    bool             enabled;
}};

/// The tab of one design as OpenRocket shows it when the user chooses it (OpenDesignsTabProbe): the
/// rows (the rocket's flight configurations, getIds() order) with column 0, the three sub-tabs, every
/// button, whether the Motors panel shows its help text instead of its table, the three tables
/// (their headers with column 0, their cells in row order, the selected rows and columns, as
/// "rows=[0] cols=[2]"), the motor mount table, and the components of the design's selection once
/// the tab took the spotlight ("[A, B]").
struct OpenDesignTabPin
{{
    /// The name of the design's tests in OpenDesignsExitGolden.
    std::string_view design;
    /// What designs.py calls its source: "example", "example-resave", "testrocket", "legacy",
    /// "coverage" or "gui".
    std::string_view kind;
    /// The row of the rocket's selected configuration (-1: the default) and getStageCount().
    int                                  selectedRow;
    int                                  stageCount;
    std::span<const ConfigurationRowPin> configurations;
    std::span<const EnabledPin>          tabs;
    int                                  currentTab;
    std::span<const EnabledPin>          buttons;
    bool                                 motorHelpShown;
    std::span<const std::string_view>    motorHeaders;
    std::span<const MotorCellPin>        motorCells;
    std::string_view                     motorSelection;
    std::span<const std::string_view>    recoveryHeaders;
    std::span<const ValueCellPin>        recoveryCells;
    std::string_view                     recoverySelection;
    std::span<const std::string_view>    stageHeaders;
    std::span<const ValueCellPin>        stageCells;
    std::string_view                     stageSelection;
    std::span<const MotorMountRowPin>    motorMounts;
    std::string_view                     designSelection;
}};

// clang-format off
// NOLINTBEGIN(modernize-use-designated-initializers): tables printed by the Java probe
// NOLINTBEGIN(modernize-raw-string-literal): the texts escaped alike, quotes and UTF-8 bytes
"""

HEADER_BOTTOM = """// NOLINTEND(modernize-raw-string-literal)
// NOLINTEND(modernize-use-designated-initializers)
// clang-format on

}  // namespace QtRocket::Gui::Test
"""

cpp_string = tables.cpp_string
boolean = tables.boolean
style = tables.style
expect_fields = tables.expect_fields


def selection(fields, line):
    expect_fields(fields, 3, line)
    return "rows=%s cols=%s" % (fields[1], fields[2])


def parse(lines):
    colours = None
    designs = []
    current = None
    for line in lines:
        line = line.rstrip("\n")
        fields = line.split("\t")
        tag = fields[0]
        if tag == "COLORS":
            expect_fields(fields, 3, line)
            colours = (tables.colour(fields[1], line), tables.colour(fields[2], line))
        elif tag == "D":
            expect_fields(fields, 3, line)
            current = {"design": fields[1], "kind": fields[2], "configurations": [], "tabs": [], "buttons": [],
                       "motorHeaders": [], "motorCells": [], "recoveryHeaders": [], "recoveryCells": [],
                       "stageHeaders": [], "stageCells": [], "mounts": []}
            designs.append(current)
        elif tag == "S":
            expect_fields(fields, 3, line)
            current["selected"] = int(fields[1])
            current["stages"] = int(fields[2])
        elif tag == "C":
            row = tables.configuration(fields, line)
            if int(fields[1]) != len(current["configurations"]):
                raise SystemExit("rows out of order: " + line)
            current["configurations"].append(row)
        elif tag == "TAB":
            expect_fields(fields, 4, line)
            if int(fields[1]) != len(current["tabs"]):
                raise SystemExit("sub-tabs out of order: " + line)
            current["tabs"].append("    {%s, %s}," % (cpp_string(fields[2]), boolean(fields[3])))
        elif tag == "TABSEL":
            expect_fields(fields, 2, line)
            current["currentTab"] = int(fields[1])
        elif tag == "B":
            expect_fields(fields, 4, line)
            current["buttons"].append("    {%s, %s}," % (cpp_string(fields[1] + "." + fields[2]),
                                                        boolean(fields[3])))
        elif tag == "HELP":
            expect_fields(fields, 2, line)
            current["help"] = boolean(fields[1])
        elif tag in ("MH", "RH", "TH"):
            expect_fields(fields, 3, line)
            headers = current[{"MH": "motorHeaders", "RH": "recoveryHeaders", "TH": "stageHeaders"}[tag]]
            if int(fields[1]) != len(headers):
                raise SystemExit("columns out of order: " + line)
            headers.append(fields[2])
        elif tag == "M0":
            expect_fields(fields, 4, line)
            style(fields[3], line, regular_only=True)
            current["configurations"][int(fields[1])]["name"] = fields[2]
        elif tag == "M":
            current["motorCells"].append(tables.motor_cell_row(fields, line))
        elif tag in ("R", "T"):
            current["recoveryCells" if tag == "R" else "stageCells"].append(tables.value_cell_row(fields, line))
        elif tag in ("MS", "RS", "TS"):
            current[{"MS": "motorSelection", "RS": "recoverySelection", "TS": "stageSelection"}[tag]] = \
                selection(fields, line)
        elif tag == "P":
            row = tables.motor_mount_row(fields, line)
            if int(fields[1]) != len(current["mounts"]):
                raise SystemExit("mount rows out of order: " + line)
            current["mounts"].append(row)
        elif tag == "DS":
            expect_fields(fields, 2, line)
            current["designSelection"] = fields[1]
        elif tag == "AFTER":
            expect_fields(fields, 4, line)
            if fields[1:] != ["false", "false", "false"]:
                raise SystemExit("opening the tab changed the design: " + line)
            current["after"] = True
        else:
            raise SystemExit("unexpected line: " + line)
    if colours is None:
        raise SystemExit("no COLORS line")
    for design in designs:
        if "after" not in design:
            raise SystemExit("no AFTER line for " + design["design"])
    return colours, designs


def main():
    probe, header, commit = sys.argv[1:4]
    with open(probe, encoding="utf-8") as f:
        (text, dim), designs = parse(f.readlines())

    out = [HEADER_TOP.format(commit=commit, text=text, dim=dim)]
    table = []
    for design in designs:
        name = tables.ident(design["design"])
        rows = [tables.configuration_row(row, design["design"]) for row in design["configurations"]]
        names = {}
        for part, element, key in (("Configurations", "ConfigurationRowPin", None),
                                   ("Tabs", "EnabledPin", "tabs"),
                                   ("Buttons", "EnabledPin", "buttons"),
                                   ("MotorHeaders", "std::string_view", "motorHeaders"),
                                   ("MotorCells", "MotorCellPin", "motorCells"),
                                   ("RecoveryHeaders", "std::string_view", "recoveryHeaders"),
                                   ("RecoveryCells", "ValueCellPin", "recoveryCells"),
                                   ("StageHeaders", "std::string_view", "stageHeaders"),
                                   ("StageCells", "ValueCellPin", "stageCells"),
                                   ("MotorMounts", "MotorMountRowPin", "mounts")):
            names[part] = "kOpen" + part + name
            if key is None:
                lines = rows
            elif key.endswith("Headers"):
                lines = ["    %s," % cpp_string(header_text) for header_text in design[key]]
            else:
                lines = design[key]
            tables.array(out, element, names[part], lines)
        table.append("    {%s, %s, %d, %d, %s, %s, %d, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s}," % (
            cpp_string(design["design"]), cpp_string(design["kind"]), design["selected"], design["stages"],
            names["Configurations"], names["Tabs"], design["currentTab"], names["Buttons"], design["help"],
            names["MotorHeaders"], names["MotorCells"], cpp_string(design["motorSelection"]),
            names["RecoveryHeaders"], names["RecoveryCells"], cpp_string(design["recoverySelection"]),
            names["StageHeaders"], names["StageCells"], cpp_string(design["stageSelection"]),
            names["MotorMounts"], cpp_string(design["designSelection"])))
    tables.array(out, "OpenDesignTabPin", "kOpenDesignTabs", table)
    out.append(HEADER_BOTTOM)
    with open(header, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    # The repository's style (its .clang-format, wherever the header is written: generate.sh --check
    # writes it into a temporary directory), so that a run reproduces the committed header byte for byte.
    style_file = pathlib.Path(__file__).resolve().parents[3] / ".clang-format"
    clang_format = os.environ.get("CLANG_FORMAT", "clang-format")
    subprocess.run([clang_format, "-i", f"--style=file:{style_file}", header], check=True)


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Writes tests/gui/figure/RocketInfoPins.h from RocketInfoProbe's output.

usage: gen_rocket_info_pins.py PROBE_OUTPUT HEADER COMMIT

PROBE_OUTPUT is the probe's standard output (generate.sh sends OpenRocket's log to standard error).
Every double of the probe is Double.toHexString (exact) and goes into the header as a C++ hexadecimal
floating literal. The layout of a recorded text is reduced to what does not depend on the font: its row
((y - y1) / line and (y2 - y) / line) and whether it starts at the left margin or ends at the right one.
"""
import os
import pathlib
import subprocess
import sys

HEADER_TOP = """#pragma once

// GENERATED by tools/openrocket-gui-pins/generate.sh (rocket-info/gen_rocket_info_pins.py from the
// output of rocket-info/probe/RocketInfoProbe.java: OpenRocket's RocketPanel.updateExtras() and
// RocketInfo, headless with SwingPreferences and FlatLaf Light; see RocketInfoGolden in
// rocket_info_golden_tests.cpp); do not edit.

#include <array>
#include <limits>
#include <ostream>
#include <span>
#include <string_view>

#include "QtRocket/figure/FigureView.h"

namespace QtRocket::Gui::Test
{{

/// The OpenRocket commit the pins come from.
inline constexpr std::string_view kRocketInfoPinsCommit = "{commit}";

/// What one recorded call of RocketInfo.paint() drew: a text (drawGlyphVector()) or the fill of a
/// caret (Caret.paint()).
enum class InfoPaintKind
{{
    TEXT,
    CG_CARET,
    CP_CARET,
}};

/// The font of a text: RocketInfo's font or smallFont (a caret has none).
enum class InfoPaintFont
{{
    REGULAR,
    SMALL,
    NONE,
}};

/// The theme colour Java drew with (FlatLaf Light): OR.colors.text, text.dim, error, cg, cp.
enum class InfoPaintColour
{{
    TEXT,
    TEXT_DIM,
    ERROR,
    CG,
    CP,
}};

/// One recorded call, in the order of the paint into the visible rectangle (0, 0, 1000, 700).
struct InfoPaintPin
{{
    InfoPaintKind   kind;
    InfoPaintFont   font;
    InfoPaintColour colour;
    /// The colour's components as Java drew it.
    int red;
    int green;
    int blue;
    /// The text (empty for a caret).
    std::string_view text;
    /// The baseline of a text (the centre of a caret) in lines below the first row's baseline,
    /// (y - y1) / line, and in lines above the bottom row's, (y2 - y) / line.
    double row;
    double rowFromBottom;
    /// Whether a text starts at the left margin (x = x1) and whether it ends at the right one (x
    /// + its visual width = x2).
    bool leftAligned;
    bool rightAligned;
}};

/// Where RocketPanel.updateExtras() puts the carets for a figure in @p view at @p rotation
/// (RocketFigure.setRotation()); @p offsetRotation is getRotation(true).
struct CaretPositionPin
{{
    FigureView view;
    double     rotation;
    double     offsetRotation;
    double     cgX;
    double     cgY;
    double     cpX;
    double     cpY;
}};

/// One design as RocketPanel.updateExtras() shows it: computePhysics() for the rocket's selected
/// configuration (FlightConditions of it at the CP parameters' Mach number or the preferences'
/// 0.3, the angle of attack or 0, the roll rate or 0, the wind direction when set; the worst CP
/// unless the wind direction is set), what it set on RocketInfo, its texts, the carets in five
/// views, and RocketInfo painted with the warnings shown and, when there are any, hidden.
struct RocketInfoScenarioPin
{{
    /// The scenario's name in the probe: "<source>:<design>".
    std::string_view name;
    /// The scenario as a test name: letters and digits.
    std::string_view testName;
    /// "example" (a file of data/examples), "testrocket" (a TestRockets maker) or "special" (a
    /// design of the probe: see rocket_info_golden_tests.cpp).
    std::string_view source;
    std::string_view design;
    /// The CP parameters of RocketPanel (NaN: the default).
    double cpMach;
    double cpAOA;
    double cpTheta;
    double cpRoll;
    /// RocketPhysics and RocketInfo's other numbers: the length, the diameter, the CP and the CG
    /// (x, y, z, weight), the masses, whether the configuration has motors.
    double                length;
    double                diameter;
    std::array<double, 4> cp;
    std::array<double, 4> cg;
    double                massWithMotors;
    double                massWithoutMotors;
    bool                  hasMotors;
    /// RocketInfo's cg, cp, mach, aoa and theta.
    double infoCg;
    double infoCp;
    double mach;
    double aoa;
    double theta;
    /// getStabilityCombined(), getCg() and getCp().
    std::string_view                  stability;
    std::string_view                  cgText;
    std::string_view                  cpText;
    std::span<const std::string_view> warnings;
    std::span<const CaretPositionPin> carets;
    std::span<const InfoPaintPin>     paint;
    std::span<const InfoPaintPin>     paintWarningsHidden;
}};

/// What GoogleTest prints for the scenario of a test that failed: its name.
// NOLINTNEXTLINE(readability-identifier-naming): the name GoogleTest looks for
inline void PrintTo(const RocketInfoScenarioPin& pin, std::ostream* out)
{{
    *out << pin.name;
}}

inline constexpr double kInfoPinNaN = std::numeric_limits<double>::quiet_NaN();

// clang-format off
// NOLINTBEGIN(modernize-use-designated-initializers): tables printed by the Java probe
// NOLINTBEGIN(modernize-use-std-numbers): Java's values, some of them near a constant
// NOLINTBEGIN(modernize-raw-string-literal): the texts escaped alike, quotes and UTF-8 bytes
"""

HEADER_BOTTOM = """// NOLINTEND(modernize-raw-string-literal)
// NOLINTEND(modernize-use-std-numbers)
// NOLINTEND(modernize-use-designated-initializers)
// clang-format on

}  // namespace QtRocket::Gui::Test
"""

VIEWS = {"Side view": "FigureView::SIDE", "Top view": "FigureView::TOP", "Back view": "FigureView::BACK"}
COLOURS = {
    ("TEXT", "0,0,0,255"): "InfoPaintColour::TEXT",
    ("TEXT", "128,128,128,255"): "InfoPaintColour::TEXT_DIM",
    ("TEXT", "255,0,0,255"): "InfoPaintColour::ERROR",
    ("FILL", "0,0,255,255"): "InfoPaintColour::CG",
    ("FILL", "255,0,0,255"): "InfoPaintColour::CP",
}
# The CP roll rate of the special scenarios (the probe prints no roll).
ROLLS = {"special:simple-cp-parameters": "0x1.0p1"}


def number(text):
    if text == "NaN":
        return "kInfoPinNaN"
    if text in ("Infinity", "-Infinity"):
        return ("-" if text[0] == "-" else "") + "std::numeric_limits<double>::infinity()"
    return text


def value(text):
    return float.fromhex(text) if text not in ("NaN",) else float("nan")


def cpp_string(text):
    out = []
    for ch in text:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= code < 0x7F:
            out.append(ch)
        else:
            # UTF-8 bytes as escapes (the core's texts are UTF-8 std::string).
            for byte in ch.encode("utf-8"):
                out.append("\\x%02X" % byte)
            out.append('" "')
    literal = '"' + "".join(out) + '"'
    # No empty literal after a final escape.
    return literal[:-4] + '"' if literal.endswith('" ""') else literal


def ident(name):
    source, design = name.split(":", 1)
    words = []
    for part in [source] + design.replace(".ork", "").replace("-", " ").replace("/", " ").split():
        cleaned = "".join(c for c in part if c.isalnum())
        if cleaned:
            words.append(cleaned[0].upper() + cleaned[1:])
    return "".join(words)


def parse(lines):
    scenarios = []
    current = None
    paint = None
    for line in lines:
        line = line.rstrip("\n")
        if line.startswith("S "):
            current = {"name": line[2:], "W": [], "K": [], "paints": []}
            scenarios.append(current)
        elif line.startswith("N "):
            current["N"] = line[2:].split(" ")
        elif line.startswith("V "):
            current["V"] = dict(item.split("=", 1) for item in line[2:].split(" "))
        elif line.startswith("X "):
            current["X"] = line[2:].split("\t")
        elif line.startswith("W "):
            current["W"].append(line[2:])
        elif line.startswith("K "):
            parts = line[2:].split(" ")
            view = parts[0] + " " + parts[1]
            current["K"].append((view, parts[2:]))
        elif line.startswith("P "):
            parts = line[2:].split(" ")
            paint = {"show": parts[0] == "true", "frame": [value(p) for p in parts[1:]], "items": []}
            current["paints"].append(paint)
        elif line.startswith("T "):
            head, text = line[2:].split(" | ", 1)
            font, colour, x, y, width = head.split(" ")
            paint["items"].append(("TEXT", font, colour, value(x), value(y), value(width), text))
        elif line.startswith("F "):
            colour, cx, cy, w, h = line[2:].split(" ")
            paint["items"].append(("FILL", "", colour, value(cx), value(cy), 0.0, ""))
        elif line.startswith("D "):
            raise SystemExit("unexpected draw: " + line)
    return scenarios


def paint_rows(paint):
    line, x1, x2, y1, y2 = paint["frame"]
    rows = []
    for kind, font, colour, x, y, width, text in paint["items"]:
        colour_key = COLOURS[(kind, colour)]
        red, green, blue, _ = colour.split(",")
        if kind == "TEXT":
            pin_kind = "InfoPaintKind::TEXT"
            pin_font = {"regular": "InfoPaintFont::REGULAR", "small": "InfoPaintFont::SMALL"}[font]
            left = abs(x - x1) < 1e-2
            right = abs(x + width - x2) < 1e-2
        else:
            pin_kind = "InfoPaintKind::CG_CARET" if colour_key.endswith("CG") else "InfoPaintKind::CP_CARET"
            pin_font = "InfoPaintFont::NONE"
            left = right = False
        row = (y - y1) / line
        from_bottom = (y2 - y) / line
        rows.append("    {%s, %s, %s, %s, %s, %s, %s, %r, %r, %s, %s}," % (
            pin_kind, pin_font, colour_key, red, green, blue, cpp_string(text), round(row, 6),
            round(from_bottom, 6), "true" if left else "false", "true" if right else "false"))
    return rows


def main():
    probe, header, commit = sys.argv[1:4]
    with open(probe, encoding="utf-8") as f:
        scenarios = parse(f.readlines())
    out = [HEADER_TOP.format(commit=commit)]
    entries = []
    for s in scenarios:
        name = s["name"]
        tid = ident(name)
        source, design = name.split(":", 1)
        n = s["N"]
        v = s["V"]
        x = s["X"]
        out.append("inline constexpr auto kInfoWarnings%s = std::to_array<std::string_view>({%s});" % (
            tid, ", ".join(cpp_string(w) for w in s["W"])) if s["W"] else
            "inline constexpr std::array<std::string_view, 0> kInfoWarnings%s{};" % tid)
        out.append("inline constexpr auto kInfoCarets%s = std::to_array<CaretPositionPin>({" % tid)
        for view, values in s["K"]:
            out.append("    {%s, %s}," % (VIEWS[view], ", ".join(number(t) for t in values)))
        out.append("});")
        shown = [p for p in s["paints"] if p["show"]]
        hidden = [p for p in s["paints"] if not p["show"]]
        out.append("inline constexpr auto kInfoPaint%s = std::to_array<InfoPaintPin>({" % tid)
        out.extend(paint_rows(shown[0]))
        out.append("});")
        if hidden:
            out.append("inline constexpr auto kInfoPaintHidden%s = std::to_array<InfoPaintPin>({" % tid)
            out.extend(paint_rows(hidden[0]))
            out.append("});")
            hidden_name = "kInfoPaintHidden" + tid
        else:
            out.append("inline constexpr std::array<InfoPaintPin, 0> kInfoPaintHidden%s{};" % tid)
            hidden_name = "kInfoPaintHidden" + tid
        special = source == "special"
        cp_mach = number(v["mach"]) if special and v["mach"] != "0x1.3333333333333p-2" else "kInfoPinNaN"
        cp_aoa = number(v["aoa"]) if special else "kInfoPinNaN"
        cp_theta = number(v["theta"]) if special else "kInfoPinNaN"
        cp_roll = ROLLS.get(name, "kInfoPinNaN")
        entries.append(
            "    RocketInfoScenarioPin{%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, {%s}, {%s}, %s, %s, %s, %s, %s, %s, %s, "
            "%s, %s, %s, %s, kInfoWarnings%s, kInfoCarets%s, kInfoPaint%s, %s}," % (
                cpp_string(name), cpp_string(tid), cpp_string(source), cpp_string(design), cp_mach, cp_aoa,
                cp_theta, cp_roll, number(n[0]), number(n[1]), ", ".join(number(t) for t in n[2:6]),
                ", ".join(number(t) for t in n[6:10]), number(n[10]), number(n[11]), n[12],
                number(v["cg"]), number(v["cp"]), number(v["mach"]), number(v["aoa"]), number(v["theta"]),
                cpp_string(x[0]), cpp_string(x[1]), cpp_string(x[2]), tid, tid, tid, hidden_name))
        out.append("")
    out.append("/// Every scenario, in the probe's order.")
    out.append("inline constexpr auto kRocketInfoScenarios = std::to_array<RocketInfoScenarioPin>({")
    out.extend(entries)
    out.append("});")
    out.append("")
    out.append(HEADER_BOTTOM)
    with open(header, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    # The repository's style (its .clang-format, wherever the header is written: generate.sh
    # --check writes it into a temporary directory), so that a run reproduces the committed
    # header byte for byte.
    style = pathlib.Path(__file__).resolve().parents[3] / ".clang-format"
    clang_format = os.environ.get("CLANG_FORMAT", "clang-format")
    subprocess.run([clang_format, "-i", f"--style=file:{style}", header], check=True)


if __name__ == "__main__":
    main()

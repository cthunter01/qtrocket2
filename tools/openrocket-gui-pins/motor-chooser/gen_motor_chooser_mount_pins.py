#!/usr/bin/env python3
"""Writes tests/gui/dialogs/motor/MotorChooserPins.h from MotorChooserMountsProbe's output.

usage: gen_motor_chooser_mount_pins.py PROBE_OUTPUT HEADER COMMIT

PROBE_OUTPUT is the probe's standard output (generate.sh sends OpenRocket's log to standard error); the
probe's Javadoc describes its lines. Every double is Double.toHexString (exact) and goes into the header as
a C++ hexadecimal floating literal (Java's "Infinity" as std::numeric_limits<double>::infinity()). The
probe runs the designs twice, as OpenRocket does and with QtRocket's fix made from outside (its FIXED
lines); the header holds the first run, and of the second what differs from it: the opens and answers, and
the preferred curves of a design. The model rows of the tables are one flat array; a table names its part
of it by its first index and its count.
"""
import os
import pathlib
import subprocess
import sys

HEADER_TOP = """#pragma once

// GENERATED by tools/openrocket-gui-pins/generate.sh (motor-chooser/gen_motor_chooser_mount_pins.py from
// the output of motor-chooser/probe/MotorChooserMountsProbe.java: OpenRocket's real
// ThrustCurveMotorSelectionPanel, headless, opened as a design window's motor chooser for every acting
// motor mount in every flight configuration of the 16 example designs, the mount's limits applied; see
// MotorChooserMountsGolden in motor_chooser_mounts_golden_tests.cpp); do not edit.

#include <array>
#include <cstdint>
#include <limits>
#include <string_view>

namespace QtRocket::Gui::Test
{{

/// The OpenRocket commit the pins come from.
inline constexpr std::string_view kMotorChooserMountPinsCommit = "{commit}";

/// The texts typed into the search field at a mount's first open, in order.
inline constexpr std::array<std::string_view, {search_count}> kMotorChooserMountSearches{{{{{searches}}}}};

/// An example design: its file in data/examples, its flight configurations (Rocket.getIds()) and its
/// acting motor mounts (MotorMount.isMotorMount(), in the order of the component tree).
struct MotorChooserMountDesignPin
{{
    std::string_view design;
    int              configurations;
    int              mounts;
}};

/// An acting motor mount of a design: its index among the design's, its component's name, its motor
/// mount diameter (getMotorMountDiameter()) and its length, settled.
struct MotorChooserMountPin
{{
    std::string_view design;
    int              mount;
    std::string_view name;
    double           diameter;
    double           length;
}};

/// A table the chooser showed: the MD5 of its rows ("<model row>\\t<the six column texts>\\n" in the
/// view's order, UTF-8) and its model rows in the view's order, kMotorChooserMountRowIndices[firstRow]
/// onwards.
struct MotorChooserMountRowsPin
{{
    std::string_view md5;
    int              rows;
    int              firstRow;
}};

/// The chooser opened for the mount @p mount in the flight configuration @p configuration (its index
/// in Rocket.getIds()), after setMotorMountAndConfig() and the dialog's open() (selectMotorFromTable()),
/// and what its OK answered. A set is its index in the database's sets (-1 for none), a curve its index
/// in its set (-1 for none).
struct MotorChooserMountOpenPin
{{
    std::string_view design;
    int              configuration;
    int              mount;
    /// The mount's motor configuration in the flight configuration: its motor (-1, -1 without one),
    /// ejection delay, the delay's text (ThrustCurveMotor.getDelayString(delay, "Plugged")) and nozzle
    /// exit diameter.
    int              configuredSet;
    int              configuredCurve;
    double           configuredDelay;
    std::string_view configuredDelayText;
    double           configuredNozzle;
    /// The filter panel: the two limit boxes, the thumbs of the diameter and length sliders, the
    /// filter's limits (a diameter limit of none: has... false) and the mount's dimensions label.
    bool             limitDiameter;
    bool             limitLength;
    int              diameterLow;
    int              diameterHigh;
    int              lengthLow;
    int              lengthHigh;
    bool             hasMinimumDiameter;
    double           minimumDiameter;
    bool             hasMaximumDiameter;
    double           maximumDiameter;
    double           minimumLength;
    double           maximumLength;
    std::string_view mountLabel;
    /// "Number of motors:", the table (kMotorChooserMountRows by its MD5) and its selected view row (-1
    /// for none).
    std::string_view motorsLabel;
    int              rows;
    std::string_view md5;
    int              selectedRow;
    /// The selected motor (getSelectedMotor()).
    int              selectedSet;
    int              selectedCurve;
    /// The curve list: enabled, the set of its curves (-1 for an empty list), their indices in it, in
    /// its order, joined by ',', and its selected item (-1 for none). The list can show the curves of
    /// another set than the selected one (a configuration without a motor leaves it as it was).
    bool             curvesEnabled;
    int              curveSet;
    std::string_view curves;
    int              curveIndex;
    /// The delay list's items joined by '|' and its text ("null" for no item selected), the selected
    /// delay, nozzle exit diameter and the nozzle's maximum.
    std::string_view delayItems;
    std::string_view delayText;
    double           delay;
    double           nozzle;
    double           nozzleMaximum;
    /// OK's answer: the motor (-1, -1 for none), the delay and the nozzle exit diameter.
    int              answerSet;
    int              answerCurve;
    double           answerDelay;
    double           answerNozzle;
}};

/// A text typed into the search field at the mount's first open (the open of the same design,
/// configuration and mount): the rows shown.
struct MotorChooserMountSearchPin
{{
    std::string_view design;
    int              configuration;
    int              mount;
    std::string_view text;
    int              rows;
    std::string_view md5;
}};

/// The node of the preferred curves (PreferredThrustCurveMotors) after a design's opens, its keys sorted.
struct MotorChooserMountPreferredPin
{{
    std::string_view design;
    std::string_view digest;
    bool             value;
}};

// clang-format off
// NOLINTBEGIN(modernize-use-designated-initializers): tables printed by the Java probe
"""

HEADER_BOTTOM = """// NOLINTEND(modernize-use-designated-initializers)
// clang-format on

}  // namespace QtRocket::Gui::Test
"""

KINDS = ("DESIGN", "MOUNT", "OPEN", "ROWS", "SEARCH", "ANSWER", "PREFERRED")
FIELDS = {"DESIGN": 3, "MOUNT": 5, "OPEN": 32, "ROWS": 3, "SEARCH": 6, "ANSWER": 7, "PREFERRED": 3}


def fail(message):
    raise SystemExit("gen_motor_chooser_mount_pins.py: " + message)


def cpp_string(text):
    for ch in text:
        if not 0x20 <= ord(ch) < 0x7F:
            fail("a non-ASCII text: %r" % text)
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def cpp_double(text):
    if text == "Infinity":
        return "std::numeric_limits<double>::infinity()"
    if text in ("-Infinity", "NaN"):
        fail("a number the pins do not expect: " + text)
    float.fromhex(text)
    return text


def optional_double(text):
    """A limit that may be none: (has, value)."""
    if text == "null":
        return "false", "0.0"
    return "true", cpp_double(text)


def boolean(text):
    if text not in ("true", "false"):
        fail("not a boolean: " + text)
    return text


def integer(text):
    return str(int(text))


def thumbs(text):
    low, high = text.split(",")
    return integer(low), integer(high)


def parse(lines):
    runs = {"": {k: [] for k in KINDS}, "FIXED": {k: [] for k in KINDS}}
    for line in lines:
        parts = line.rstrip("\n").split("\t")
        kind = parts[0]
        prefix = ""
        if kind.startswith("FIXED"):
            prefix, kind = "FIXED", kind[len("FIXED"):]
        if kind not in KINDS:
            fail("an unknown line: %r" % line)
        if len(parts) - 1 != FIELDS[kind]:
            fail("%d fields expected: %r" % (FIELDS[kind], line))
        runs[prefix][kind].append(parts[1:])
    return runs


def opens(run):
    """The run's opens with their answers, keyed by (design, configuration, mount), in order."""
    answers = {tuple(a[:3]): a[3:] for a in run["ANSWER"]}
    result = {}
    for o in run["OPEN"]:
        key = tuple(o[:3])
        if key in result or key not in answers:
            fail("an open without its answer, or twice: %s" % (key,))
        result[key] = o[3:] + answers.pop(key)
    if answers:
        fail("answers without an open: %s" % list(answers))
    return result


def preferred(run):
    by_design = {}
    for design, digest, value in run["PREFERRED"]:
        by_design.setdefault(design, []).append((digest, value))
    return by_design


def open_row(key, values):
    design, configuration, mount = key
    (configured_set, configured_curve, configured_delay, configured_delay_text, configured_nozzle,
     limit_diameter, limit_length, diameter_thumbs, length_thumbs, min_diameter, max_diameter, min_length,
     max_length, mount_label, motors_label, rows, md5, selected_row, selected_set, selected_curve,
     curves_enabled, curve_set, curves, curve_index, delay_items, delay_text, delay, nozzle, nozzle_maximum,
     answer_set, answer_curve, answer_delay, answer_nozzle) = values
    has_min, min_value = optional_double(min_diameter)
    has_max, max_value = optional_double(max_diameter)
    fields = [cpp_string(design), integer(configuration), integer(mount), integer(configured_set),
              integer(configured_curve), cpp_double(configured_delay), cpp_string(configured_delay_text),
              cpp_double(configured_nozzle), boolean(limit_diameter), boolean(limit_length),
              *thumbs(diameter_thumbs), *thumbs(length_thumbs), has_min, min_value, has_max, max_value,
              cpp_double(min_length), cpp_double(max_length), cpp_string(mount_label), cpp_string(motors_label),
              integer(rows), cpp_string(md5), integer(selected_row), integer(selected_set),
              integer(selected_curve), boolean(curves_enabled), integer(curve_set), cpp_string(curves),
              integer(curve_index), cpp_string(delay_items), cpp_string(delay_text), cpp_double(delay),
              cpp_double(nozzle), cpp_double(nozzle_maximum), integer(answer_set), integer(answer_curve),
              cpp_double(answer_delay), cpp_double(answer_nozzle)]
    return "    {%s}," % ", ".join(fields)


def table(out, element, name, rows, size=None):
    """Appends the table `name` of `rows` (lines of `size` elements in all; one each by default) as a
    std::array of `element` with its size spelt out, as the repository's other generated tables are:
    no std::to_array, whose constant evaluation of long lists MSVC's limits have never been tried
    with."""
    out.append("inline constexpr std::array<%s, %d> %s{{" % (element, len(rows) if size is None else size,
                                                              name))
    out.extend(rows)
    out.append("}};")


def main():
    probe, header, commit = sys.argv[1:4]
    with open(probe, encoding="utf-8") as f:
        runs = parse(f.readlines())
    plain, fixed = runs[""], runs["FIXED"]
    for kind in ("DESIGN", "MOUNT", "SEARCH"):
        if plain[kind] != fixed[kind]:
            fail("the two runs differ in their %s lines" % kind)
    if fixed["ROWS"]:
        fail("the second run showed a table the first did not")
    plain_opens, fixed_opens = opens(plain), opens(fixed)
    if list(plain_opens) != list(fixed_opens):
        fail("the two runs opened the chooser differently")
    searches = []
    for s in plain["SEARCH"]:
        if s[3] not in searches:
            searches.append(s[3])

    out = [HEADER_TOP.format(commit=commit, search_count=len(searches),
                             searches=", ".join(cpp_string(s) for s in searches))]
    out.append("/// The designs, in the order of their file names.")
    table(out, "MotorChooserMountDesignPin", "kMotorChooserMountDesigns", [
        "    {%s, %s, %s}," % (cpp_string(design), integer(configurations), integer(mounts))
        for design, configurations, mounts in plain["DESIGN"]])
    out.append("")
    out.append("/// The acting motor mounts of every design.")
    table(out, "MotorChooserMountPin", "kMotorChooserMounts", [
        "    {%s, %s, %s, %s, %s}," % (cpp_string(design), integer(mount), cpp_string(name), cpp_double(diameter),
                                      cpp_double(length))
        for design, mount, name, diameter, length in plain["MOUNT"]])
    out.append("")

    indices = []
    rows_pins = []
    for md5, count, model_rows in plain["ROWS"]:
        listed = [int(r) for r in model_rows.split(",")] if model_rows else []
        if len(listed) != int(count):
            fail("a table of %s rows lists %d" % (count, len(listed)))
        rows_pins.append("    {%s, %d, %d}," % (cpp_string(md5), len(listed), len(indices)))
        indices.extend(listed)
    shown = {row.split(", ")[0].strip(" {") for row in rows_pins}
    for values in list(plain_opens.values()):
        if cpp_string(values[16]) not in shown:
            fail("an open's table is not among the tables: " + values[16])
    out.append("/// Every table the chooser showed (an open's or a search's), once.")
    table(out, "MotorChooserMountRowsPin", "kMotorChooserMountRows", rows_pins)
    out.append("/// The model rows of the tables, table after table.")
    table(out, "std::uint16_t", "kMotorChooserMountRowIndices",
          ["    " + ", ".join(str(i) for i in indices[start:start + 20]) + ","
           for start in range(0, len(indices), 20)], len(indices))
    out.append("")
    out.append("/// Every open of the chooser, design after design, in the order the probe opened it: each flight")
    out.append("/// configuration, and in it each mount.")
    table(out, "MotorChooserMountOpenPin", "kMotorChooserMountOpens",
          [open_row(key, values) for key, values in plain_opens.items()])
    out.append("")
    out.append("/// The opens that QtRocket's fix changes, as the probe's second run gave them: opened for a")
    out.append("/// configuration with a motor, the chooser forgets the table row an earlier open selected, which")
    out.append("/// OpenRocket selects instead of the configured motor when the mount's limits hide its set.")
    table(out, "MotorChooserMountOpenPin", "kMotorChooserMountFixedOpens",
          [open_row(key, fixed_opens[key]) for key in plain_opens if fixed_opens[key] != plain_opens[key]])
    out.append("")
    out.append("/// The searches at each mount's first open.")
    table(out, "MotorChooserMountSearchPin", "kMotorChooserMountSearchRows", [
        "    {%s, %s, %s, %s, %s, %s}," % (cpp_string(design), integer(configuration), integer(mount),
                                          cpp_string(text), integer(rows), cpp_string(md5))
        for design, configuration, mount, text, rows, md5 in plain["SEARCH"]])
    out.append("")

    plain_preferred, fixed_preferred = preferred(plain), preferred(fixed)

    def preferred_rows(by_design, designs):
        return ["    {%s, %s, %s}," % (cpp_string(design), cpp_string(digest), boolean(value))
                for design in designs for digest, value in by_design.get(design, [])]

    designs = [d[0] for d in plain["DESIGN"]]
    out.append("/// The preferred curves after every design's opens.")
    table(out, "MotorChooserMountPreferredPin", "kMotorChooserMountPreferred",
          preferred_rows(plain_preferred, designs))
    changed = [d for d in designs if plain_preferred.get(d, []) != fixed_preferred.get(d, [])]
    out.append("/// The designs whose preferred curves QtRocket's fix changes, and those curves (the second run's).")
    table(out, "std::string_view", "kMotorChooserMountFixedPreferredDesigns",
          ["    %s," % cpp_string(d) for d in changed])
    table(out, "MotorChooserMountPreferredPin", "kMotorChooserMountFixedPreferred",
          preferred_rows(fixed_preferred, changed))
    out.append("")
    out.append(HEADER_BOTTOM)
    with open(header, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    # The repository's style (its .clang-format, wherever the header is written: generate.sh --check
    # writes it into a temporary directory), so that a run reproduces the committed header byte for byte.
    style = pathlib.Path(__file__).resolve().parents[3] / ".clang-format"
    clang_format = os.environ.get("CLANG_FORMAT", "clang-format")
    subprocess.run([clang_format, "-i", f"--style=file:{style}", header], check=True)


if __name__ == "__main__":
    main()

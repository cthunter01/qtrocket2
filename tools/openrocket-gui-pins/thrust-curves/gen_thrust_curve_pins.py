#!/usr/bin/env python3
"""Writes tests/gui/plot/ThrustCurvePins.h from ThrustCurvesProbe's output.

usage: gen_thrust_curve_pins.py PROBE_OUTPUT HEADER COMMIT

PROBE_OUTPUT is the probe's standard output (generate.sh sends OpenRocket's log to standard error); the
probe's Javadoc describes its lines. Every double is Double.toHexString (exact) and goes into the header as
a C++ hexadecimal floating literal, every colour as 0xRRGGBB. The lists the header holds are flat arrays;
a set, a chart or a legend names its part of one by its first index and its count.
"""
import os
import pathlib
import subprocess
import sys

HEADER_TOP = """#pragma once

// GENERATED by tools/openrocket-gui-pins/generate.sh (thrust-curves/gen_thrust_curve_pins.py from the
// output of thrust-curves/probe/ThrustCurvesProbe.java: OpenRocket's MotorInformationPanel preview and
// ThrustCurveMotorPlotDialog for every motor set of the bundled database, read back through
// JFreeChart's API, under xvfb with SwingPreferences and FlatLaf; see ThrustCurvePlotPinsGolden in
// thrust_curve_plot_golden_tests.cpp); do not edit.

#include <array>
#include <cstdint>
#include <string_view>

namespace QtRocket::Gui::Test
{{

/// The OpenRocket commit the pins come from.
inline constexpr std::string_view kThrustCurvePinsCommit = "{commit}";

/// A colour of the thrust curves, as 0xRRGGBB: Util.getPlotColor(index) (the light theme) and
/// ThrustCurveMotorSelectionPanel.getColor(index) in the dark theme (brighter().brighter()).
struct ThrustCurveColorPin
{{
    int           index;
    std::uint32_t light;
    std::uint32_t dark;
}};

/// The ranges of a chart's axes: [xMin, xMax] (the time) and [yMin, yMax] (the thrust).
struct ThrustCurveRangePin
{{
    double xMin;
    double xMax;
    double yMin;
    double yMax;
}};

/// A thrust curve of the bundled database: its manufacturer's display name, its designation and
/// its digest (the three together name one curve; {shared} curves share their digest with a curve
/// filed under another manufacturer or designation) and the number of its points.
struct ThrustCurveKeyPin
{{
    std::string_view manufacturer;
    std::string_view designation;
    std::string_view digest;
    int              points;
}};

/// A motor set of the bundled database, in ThrustCurveMotorSetDatabase.getMotorSets()'s order: its
/// manufacturer's display name and designation, its curves (kThrustCurves[firstCurve] onwards, in
/// ThrustCurveMotorComparator's order, the list ThrustCurveMotorSelectionPanel gives both charts),
/// and the axes of the preview and of the dialog with the first curve selected.
struct ThrustCurveSetPin
{{
    int                 index;
    std::string_view    manufacturer;
    std::string_view    designation;
    int                 firstCurve;
    int                 curveCount;
    ThrustCurveRangePin preview;
    ThrustCurveRangePin dialog;
}};

/// The marker JFreeChart draws at a series' points: none, or a filled square of the given size.
enum class ThrustCurveMarker
{{
    NONE,
    FILLED_SQUARE,
}};

/// A series as JFreeChart holds it: its key, paint (0xRRGGBB), stroke width, marker and number of
/// points.
struct ThrustCurveSeriesPin
{{
    std::string_view  name;
    std::uint32_t     color;
    double            lineWidth;
    ThrustCurveMarker marker;
    double            markerSize;
    int               points;
}};

/// Both charts of a motor set (kThrustCurveSets[set]) with curve @c selected chosen, in the light or
/// the dark theme: the preview's series (kThrustCurveSeries[firstPreview] onwards, in JFreeChart's
/// order: series 0 first), the dialog's, and the dialog's legend items (kThrustCurveLegend).
struct ThrustCurveChartPin
{{
    bool dark;
    int  set;
    int  selected;
    int  firstPreview;
    int  previewCount;
    int  firstDialog;
    int  dialogCount;
    int  firstLegend;
    int  legendCount;
}};

/// The thrust axis of the dialog with a force unit as the default unit: its label and its range.
struct ThrustCurveUnitPin
{{
    std::string_view unit;
    std::string_view thrustLabel;
    double           yMin;
    double           yMax;
}};

/// ThrustCurveMotorPlotDialog itself: its modality, its close operation, whether Esc closes it and
/// whether it has a default button, its chart's size after pack() (the layout's "width 600:600:,
/// height 400:400:"), whether the close button's right edge is the chart's and the button below
/// it, and its buttons' texts in order (kThrustCurveDialogButtons).
struct ThrustCurveDialogPin
{{
    std::string_view modality;
    std::string_view defaultCloseOperation;
    bool             escapeCloses;
    bool             defaultButton;
    int              chartWidth;
    int              chartHeight;
    bool             closeRightAligned;
    bool             closeBelowChart;
}};

// clang-format off
// NOLINTBEGIN(modernize-use-designated-initializers): tables printed by the Java probe
// NOLINTBEGIN(modernize-use-std-numbers): Java's values, some of them near a constant
"""

HEADER_BOTTOM = """// NOLINTEND(modernize-use-std-numbers)
// NOLINTEND(modernize-use-designated-initializers)
// clang-format on

}  // namespace QtRocket::Gui::Test
"""

TEXTS = [
    ("previewTitle", "kThrustCurvePreviewTitle", "MotorInformationPanel's chart title"),
    ("dialogWindowTitle", "kThrustCurveDialogWindowTitle", "ThrustCurveMotorPlotDialog's window title"),
    ("dialogChartTitle", "kThrustCurveDialogChartTitle", "the dialog's chart title"),
    ("dialogTimeLabel", "kThrustCurveDialogTimeLabel", "the dialog's time axis label (default units)"),
    ("dialogThrustLabel", "kThrustCurveDialogThrustLabel", "the dialog's thrust axis label (default units)"),
    ("closeButton", "kThrustCurveCloseButton", "the dialog's close button"),
]
DIALOG_KEYS = ["modality", "defaultCloseOperation", "escapeCloses", "defaultButton", "chartSize",
               "closeRightAligned", "closeBelowChart", "buttons"]
SQUARE = "Double(-3.0,-3.0,6.0,6.0) filled"


def fail(message):
    raise SystemExit("gen_thrust_curve_pins.py: " + message)


def cpp_string(text):
    for ch in text:
        if not 0x20 <= ord(ch) < 0x7F:
            fail("a non-ASCII text: %r" % text)
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def hex_double(text):
    value = float.fromhex(text)
    if value != value or value in (float("inf"), float("-inf")):
        fail("a non-finite number: " + text)
    return text


def color(text):
    if len(text) != 7 or text[0] != "#":
        fail("a colour with an alpha or of another form: " + text)
    return "0x" + text[1:]


def boolean(text):
    if text not in ("true", "false"):
        fail("not a boolean: " + text)
    return text


def fields(line, prefix, count):
    parts = line[len(prefix):].split(" | ")
    if len(parts) != count:
        fail("%d fields expected: %r" % (count, line))
    return parts


def range_pin(parts):
    return "{%s}" % ", ".join(hex_double(p) for p in parts)


def parse(lines):
    data = {"colors": [], "texts": {}, "dialog": {}, "sets": [], "charts": [], "units": [], "empty": None}
    current_set = None
    current_chart = None
    for line in lines:
        line = line.rstrip("\n")
        if line.startswith("COLOR "):
            index, light, dark = fields(line, "COLOR ", 3)
            data["colors"].append((int(index), color(light), color(dark)))
        elif line.startswith("TEXT "):
            key, text = fields(line, "TEXT ", 2)
            data["texts"][key] = text
        elif line.startswith("DIALOG "):
            key, value = fields(line, "DIALOG ", 2)
            data["dialog"][key] = value
        elif line.startswith("EMPTY "):
            data["empty"] = range_pin(fields(line, "EMPTY ", 4))
        elif line.startswith("SET "):
            index, manufacturer, designation, count = fields(line, "SET ", 4)
            if int(index) != len(data["sets"]):
                fail("the sets out of order: " + line)
            current_set = {"manufacturer": manufacturer, "designation": designation, "count": int(count),
                           "curves": [], "ranges": {}}
            data["sets"].append(current_set)
        elif line.startswith("CURVE "):
            manufacturer, designation, digest, points = fields(line, "CURVE ", 4)
            current_set["curves"].append((manufacturer, designation, digest, int(points)))
        elif line.startswith("RANGE "):
            parts = fields(line, "RANGE ", 5)
            current_set["ranges"][parts[0]] = range_pin(parts[1:])
        elif line.startswith("CHART "):
            theme, set_index, selected = fields(line, "CHART ", 3)
            if theme not in ("light", "dark"):
                fail("a theme: " + line)
            current_chart = {"dark": theme == "dark", "set": int(set_index), "selected": int(selected),
                             "preview": [], "dialog": [], "legend": []}
            data["charts"].append(current_chart)
        elif line.startswith("SERIES "):
            chart, index, name, paint, width, marker, items = fields(line, "SERIES ", 7)
            series = current_chart[chart]
            if int(index) != len(series):
                fail("the series out of order: " + line)
            if marker == "none":
                marker_pin, size = "ThrustCurveMarker::NONE", "0.0"
            elif marker == SQUARE:
                marker_pin, size = "ThrustCurveMarker::FILLED_SQUARE", "6.0"
            else:
                fail("a marker: " + line)
            series.append((name, color(paint), hex_double(width), marker_pin, size, int(items)))
        elif line.startswith("LEGEND "):
            index, label = fields(line, "LEGEND ", 2)
            if int(index) != len(current_chart["legend"]):
                fail("the legend out of order: " + line)
            current_chart["legend"].append(label)
        elif line.startswith("UNIT "):
            unit, label, y_min, y_max = fields(line, "UNIT ", 4)
            data["units"].append((unit, label, hex_double(y_min), hex_double(y_max)))
        else:
            fail("an unknown line: %r" % line)
    return data


def check(data):
    if sorted(data["texts"]) != sorted(key for key, _, _ in TEXTS):
        fail("texts: %s" % sorted(data["texts"]))
    if sorted(data["dialog"]) != sorted(DIALOG_KEYS):
        fail("dialog keys: %s" % sorted(data["dialog"]))
    keys = set()
    for s in data["sets"]:
        if len(s["curves"]) != s["count"] or sorted(s["ranges"]) != ["dialog", "preview"]:
            fail("an incomplete set: %s %s" % (s["manufacturer"], s["designation"]))
        for curve in s["curves"]:
            key = curve[:3]
            if key in keys:
                fail("two curves %s" % (key,))
            keys.add(key)
    for chart in data["charts"]:
        count = data["sets"][chart["set"]]["count"]
        if not (len(chart["preview"]) == len(chart["dialog"]) == len(chart["legend"]) == count):
            fail("an incomplete chart: %s" % chart)
    if data["empty"] is None or not data["units"] or not data["colors"]:
        fail("no empty range, units or colours")


def main():
    probe, header, commit = sys.argv[1:4]
    with open(probe, encoding="utf-8") as f:
        data = parse(f.readlines())
    check(data)
    digests = {}
    for s in data["sets"]:
        for curve in s["curves"]:
            digests[curve[2]] = digests.get(curve[2], 0) + 1
    shared = sum(count for count in digests.values() if count > 1)
    out = [HEADER_TOP.format(commit=commit, shared=shared)]

    out.append("/// The colours of curves 0 to %d (OpenRocket's ten, then again from the first)." %
               (len(data["colors"]) - 1))
    out.append("inline constexpr auto kThrustCurveColors = std::to_array<ThrustCurveColorPin>({")
    for index, light, dark in data["colors"]:
        out.append("    {%d, %s, %s}," % (index, light, dark))
    out.append("});")
    out.append("")
    for key, name, comment in TEXTS:
        out.append("/// %s." % (comment[0].upper() + comment[1:]))
        out.append("inline constexpr std::string_view %s = %s;" % (name, cpp_string(data["texts"][key])))
    out.append("")

    dialog = data["dialog"]
    width, height = dialog["chartSize"].split("x")
    out.append("/// The dialog.")
    out.append("inline constexpr ThrustCurveDialogPin kThrustCurveDialog{%s, %s, %s, %s, %d, %d, %s, %s};" % (
        cpp_string(dialog["modality"]), cpp_string(dialog["defaultCloseOperation"]),
        boolean(dialog["escapeCloses"]), boolean(dialog["defaultButton"]), int(width), int(height),
        boolean(dialog["closeRightAligned"]), boolean(dialog["closeBelowChart"])))
    buttons = [dialog["buttons"]]
    out.append("/// The dialog's buttons, in order.")
    out.append("inline constexpr auto kThrustCurveDialogButtons = std::to_array<std::string_view>({%s});" %
               ", ".join(cpp_string(b) for b in buttons))
    out.append("")
    out.append("/// The preview after MotorInformationPanel.clearData() (an empty dataset).")
    out.append("inline constexpr ThrustCurveRangePin kThrustCurveEmptyRange%s;" % data["empty"])
    out.append("")

    out.append("/// The curves of every set, set after set.")
    out.append("inline constexpr auto kThrustCurves = std::to_array<ThrustCurveKeyPin>({")
    first = []
    total = 0
    for s in data["sets"]:
        first.append(total)
        for manufacturer, designation, digest, points in s["curves"]:
            out.append("    {%s, %s, %s, %d}," % (cpp_string(manufacturer), cpp_string(designation),
                                                  cpp_string(digest), points))
            total += 1
    out.append("});")
    out.append("")
    out.append("/// Every motor set of the bundled database, in its order.")
    out.append("inline constexpr auto kThrustCurveSets = std::to_array<ThrustCurveSetPin>({")
    for index, s in enumerate(data["sets"]):
        out.append("    {%d, %s, %s, %d, %d, %s, %s}," % (
            index, cpp_string(s["manufacturer"]), cpp_string(s["designation"]), first[index], s["count"],
            s["ranges"]["preview"], s["ranges"]["dialog"]))
    out.append("});")
    out.append("")

    series_rows = []
    legend_rows = []
    chart_rows = []
    for chart in data["charts"]:
        first_preview = len(series_rows)
        series_rows.extend(chart["preview"])
        first_dialog = len(series_rows)
        series_rows.extend(chart["dialog"])
        first_legend = len(legend_rows)
        legend_rows.extend(chart["legend"])
        chart_rows.append("    {%s, %d, %d, %d, %d, %d, %d, %d, %d}," % (
            "true" if chart["dark"] else "false", chart["set"], chart["selected"], first_preview,
            len(chart["preview"]), first_dialog, len(chart["dialog"]), first_legend, len(chart["legend"])))
    out.append("/// The series of every chart, chart after chart (the preview's, then the dialog's).")
    out.append("inline constexpr auto kThrustCurveSeries = std::to_array<ThrustCurveSeriesPin>({")
    for name, paint, width, marker, size, items in series_rows:
        out.append("    {%s, %s, %s, %s, %s, %d}," % (cpp_string(name), paint, width, marker, size, items))
    out.append("});")
    out.append("")
    out.append("/// The dialog's legend items of every chart, chart after chart.")
    out.append("inline constexpr auto kThrustCurveLegend = std::to_array<std::string_view>({")
    for label in legend_rows:
        out.append("    %s," % cpp_string(label))
    out.append("});")
    out.append("")
    out.append("/// Every set of more than one curve with its first and its last curve selected (light), then")
    out.append("/// the set with the most curves in the dark theme.")
    out.append("inline constexpr auto kThrustCurveCharts = std::to_array<ThrustCurveChartPin>({")
    out.extend(chart_rows)
    out.append("});")
    out.append("")
    out.append("/// The set whose dialog the force units are pinned with (its first curve selected): the first set")
    out.append("/// of more than one curve.")
    multi = next(i for i, s in enumerate(data["sets"]) if s["count"] > 1)
    out.append("inline constexpr int kThrustCurveUnitSet = %d;" % multi)
    out.append("/// The dialog's thrust axis with each unit of UNITS_FORCE as the default unit.")
    out.append("inline constexpr auto kThrustCurveUnits = std::to_array<ThrustCurveUnitPin>({")
    for unit, label, y_min, y_max in data["units"]:
        out.append("    {%s, %s, %s, %s}," % (cpp_string(unit), cpp_string(label), y_min, y_max))
    out.append("});")
    out.append("")
    out.append(HEADER_BOTTOM)
    with open(header, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    # The repository's style (its .clang-format, wherever the header is written: generate.sh --check
    # writes it into a temporary directory), so that a run reproduces the committed header byte for
    # byte.
    style = pathlib.Path(__file__).resolve().parents[3] / ".clang-format"
    clang_format = os.environ.get("CLANG_FORMAT", "clang-format")
    subprocess.run([clang_format, "-i", f"--style=file:{style}", header], check=True)


if __name__ == "__main__":
    main()

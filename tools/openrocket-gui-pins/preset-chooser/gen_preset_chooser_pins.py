TEXTS = [
    ("title", "kPresetChooserTitle", "the dialog's title"),
    ("filterLabel", "kPresetChooserFilterLabel", "the label before the filter text"),
    ("favoritesLabel", "kPresetChooserFavoritesLabel", "the label below the table (HTML)"),
    ("closeButton", "kPresetChooserCloseButton", "the Close button"),
]

STEPS = {
    "open": "OPEN",
    "fore off": "FORE_OFF",
    "aft off": "AFT_OFF",
    "legacy on": "LEGACY_ON",
    "text": "TEXT",
    "legacy off": "LEGACY_OFF",
    "fore on": "FORE_ON",
    "aft on": "AFT_ON",
}

ALWAYS_OPEN = {"default": "UNSET", "false": "OFF", "true": "ON"}

WINDOW_KEYS = ["scenario", "owner", "size", "defaultButton", "escapeCloses", "table", "emptyText", "emptyRows"]


def fail(message):
    raise SystemExit("gen_preset_chooser_pins.py: " + message)


def cpp_string(text):
    out = []
    for ch in text:
        code = ord(ch)
        if ch in "\\\"":
            out.append("\\" + ch)
        elif 0x20 <= code < 0x7F:
            out.append(ch)
        elif 0xA0 <= code <= 0xFFFF and not 0xD800 <= code <= 0xDFFF:
            out.append("\\u%04X" % code)
        else:
            fail("a character that cannot be written: %r" % text)
    return '"' + "".join(out) + '"'


def hex_double(text):
    value = float.fromhex(text)
    if value != value or value in (float("inf"), float("-inf")):
        fail("a non-finite number: " + text)
    return text


def boolean(text):
    if text not in ("true", "false"):
        fail("not a boolean: " + text)
    return text


def fields(line, prefix, count):
    parts = line[len(prefix):].split(" | ")
    if len(parts) != count:
        fail("%d fields expected: %r" % (count, line))
    return parts


def box_pin(parts):
    if parts == ["none"]:
        return "{false, \"\", \"\", false, false}"
    if len(parts) != 4:
        fail("a box: %r" % parts)
    text, tip, shown, checked = parts
    return "{true, %s, %s, %s, %s}" % (cpp_string(text), cpp_string("" if tip == "null" else tip), boolean(shown),
                                      boolean(checked))


def parse(lines):
    data = {"database": None, "texts": {}, "scenarios": [], "actions": [], "window": {}, "focus": [], "keys": []}
    current = None
    for line in lines:
        line = line.rstrip("\n")
        if line.startswith("DATABASE "):
            data["database"] = [int(p) for p in fields(line, "DATABASE ", 3)]
        elif line.startswith("TEXT "):
            key, text = fields(line, "TEXT ", 2)
            data["texts"][key] = text
        elif line.startswith("SCENARIO "):
            index, name, component, type_, fore, aft, always = fields(line, "SCENARIO ", 7)
            if int(index) != len(data["scenarios"]):
                fail("the scenarios out of order: " + line)
            if always not in ALWAYS_OPEN:
                fail("an AlwaysOpenPreset setting: " + line)
            current = {"name": name, "component": component, "type": type_, "matchFore": boolean(fore),
                       "matchAft": boolean(aft), "alwaysOpen": ALWAYS_OPEN[always], "radii": [], "columns": [],
                       "index": None, "boxes": {}, "filters": {}, "fixed": None, "always": None, "views": [],
                       "prefs": None}
            data["scenarios"].append(current)
        elif line.startswith("RADII "):
            for part in line[len("RADII "):].split(" | "):
                name, fore, aft = part.rsplit(" ", 2)
                current["radii"].append((name, hex_double(fore), hex_double(aft)))
        elif line.startswith("COLUMN "):
            header, model, shown = fields(line, "COLUMN ", 3)
            current["columns"].append((header, int(model), boolean(shown)))
        elif line.startswith("INDEX "):
            current["index"] = [int(p) for p in fields(line, "INDEX ", 3)]
        elif line.startswith("BOX "):
            parts = line[len("BOX "):].split(" | ")
            if parts[0] not in ("legacy", "fore", "aft") or parts[0] in current["boxes"]:
                fail("a box: " + line)
            current["boxes"][parts[0]] = box_pin(parts[1:])
        elif line.startswith("FILTER "):
            parts = line[len("FILTER "):].split(" | ")
            if parts[0] not in ("fore", "aft"):
                fail("a filter: " + line)
            if parts[1:] == ["none"]:
                current["filters"][parts[0]] = None
            elif len(parts) == 3:
                current["filters"][parts[0]] = (hex_double(parts[1]), hex_double(parts[2]))
            else:
                fail("a filter: " + line)
        elif line.startswith("FIXED aft | "):
            openrocket, fixed, epsilon = fields(line, "FIXED aft | ", 3)
            current["fixed"] = (hex_double(openrocket), hex_double(fixed), hex_double(epsilon))
        elif line.startswith("ALWAYS "):
            text, checked = fields(line, "ALWAYS ", 2)
            current["always"] = (text, boolean(checked))
        elif line.startswith("VIEW "):
            step, text, view = fields(line, "VIEW ", 3)
            if step not in STEPS or (step != "text" and text):
                fail("a view: " + line)
            if not view.startswith("rows ") or " md5 " not in view:
                fail("a view: " + line)
            current["views"].append((STEPS[step], text, view))
        elif line.startswith("PREFS "):
            current["prefs"] = [boolean(p) for p in fields(line, "PREFS ", 2)]
        elif line.startswith("ACTION "):
            data["actions"].append(parse_action(line))
        elif line.startswith("DIALOG "):
            key, value = fields(line, "DIALOG ", 2)
            if key in data["window"]:
                fail("a window fact twice: " + line)
            data["window"][key] = value
        elif line.startswith("FOCUS "):
            index, descriptor = fields(line, "FOCUS ", 2)
            if int(index) != len(data["focus"]):
                fail("the focus order out of order: " + line)
            data["focus"].append(descriptor)
        elif line.startswith("KEY "):
            start_row, start_column, key, row, column, row_lead, column_lead = fields(line, "KEY ", 7)
            if key not in ("enter", "shift enter"):
                fail("a key: " + line)
            empty = start_row == "empty"
            data["keys"].append(("true" if empty else "false", -1 if empty else int(start_row), int(start_column),
                                 "ENTER" if key == "enter" else "SHIFT_ENTER", int(row), int(column), int(row_lead),
                                 int(column_lead)))
        else:
            fail("an unknown line: %r" % line)
    return data


def parse_action(line):
    scenario, what, applied, stored = fields(line, "ACTION ", 4)
    applied = "" if applied == "none" else applied
    if what == "close with view row 3 selected":
        return (int(scenario), "CLOSE", 3, -1, applied, sorted_tables(stored), "", "false")
    if what == "close without a selection":
        return (int(scenario), "CLOSE", -1, -1, applied, sorted_tables(stored), "", "false")
    prefix = "double click on view row 5, view column "
    if what.startswith(prefix):
        return (int(scenario), "DOUBLE_CLICK", 5, int(what[len(prefix):]), applied, sorted_tables(stored), "",
                "false")
    if what in ("always open clicked", "always open clicked again"):
        preference, _, box = stored.partition(" (box ")
        if not box.endswith(")"):
            fail("an action: " + line)
        return (int(scenario), "ALWAYS_OPEN_CLICK", -1, -1, applied, "", preference, boolean(box[:-1]))
    fail("an action: " + line)


def sorted_tables(stored):
    """The keys in UTF-8 byte order (Java sorted them by UTF-16 code units)."""
    if not stored:
        return ""
    entries = stored.split(";")
    return ";".join(sorted(entries, key=lambda e: e.partition("=")[0].encode("utf-8")))


def check(data):
    if data["database"] is None:
        fail("no DATABASE line")
    if sorted(data["texts"]) != sorted(key for key, _, _ in TEXTS):
        fail("texts: %s" % sorted(data["texts"]))
    for s in data["scenarios"]:
        if s["index"] is None or sorted(s["boxes"]) != ["aft", "fore", "legacy"] or sorted(s["filters"]) != [
                "aft", "fore"] or s["always"] is None or s["prefs"] is None or not s["views"] or not s["columns"]:
            fail("an incomplete scenario: %s" % s["name"])
        if s["fixed"] is not None and (s["filters"]["aft"] is None or s["filters"]["aft"][0] != s["fixed"][0]):
            fail("a fixed aft filter without OpenRocket's: %s" % s["name"])
    if not data["actions"]:
        fail("no actions")
    if sorted(data["window"]) != sorted(WINDOW_KEYS) or not data["focus"] or not data["keys"]:
        fail("the window: %s" % sorted(data["window"]))
    for action in data["actions"]:
        if not 0 <= action[0] < len(data["scenarios"]):
            fail("an action of no scenario: %s" % (action,))


def table(out, element, name, rows):
    """Appends the table `name` of `rows` as a std::array of `element` with its size spelt out (as the
    repository's other generated tables are)."""
    out.append("inline constexpr std::array<%s, %d> %s{{" % (element, len(rows), name))
    out.extend(rows)
    out.append("}};")


def main():
    probe, header, commit = sys.argv[1:4]
    with open(probe, encoding="utf-8") as f:
        data = parse(f.readlines())
    check(data)
    files, read, kept = data["database"]
    out = [HEADER_TOP.format(commit=commit, files=files, read=read, kept=kept)]
    for key, name, comment in TEXTS:
        out.append("/// %s." % (comment[0].upper() + comment[1:]))
        out.append("inline constexpr std::string_view %s = %s;" % (name, cpp_string(data["texts"][key])))
    out.append("")

    radii_rows = []
    column_rows = []
    view_rows = []
    scenario_rows = []
    for index, s in enumerate(data["scenarios"]):
        first_radii = len(radii_rows)
        radii_rows.extend("    {%s, %s, %s}," % (cpp_string(name), fore, aft) for name, fore, aft in s["radii"])
        first_column = len(column_rows)
        column_rows.extend("    {%s, %d, %s}," % (cpp_string(header), model, shown)
                           for header, model, shown in s["columns"])
        first_view = len(view_rows)
        view_rows.extend("    {PresetChooserStep::%s, %s, %s}," % (step, cpp_string(text), cpp_string(view))
                         for step, text, view in s["views"])
        fore = s["filters"]["fore"]
        aft = s["filters"]["aft"]
        aft_value = aft[0] if aft is not None else "0.0"
        aft_tolerance = aft[1] if aft is not None else "0.0"
        openrocket_aft = aft_value
        if s["fixed"] is not None:
            openrocket_aft, aft_value, aft_tolerance = s["fixed"]
        legacy_column, fore_column, aft_column = s["index"]
        scenario_rows.append(
            "    {%d, %s, %s, %s, %s, %s, PresetChooserAlwaysOpen::%s, %d, %d, %d, %d, %d, %d, %d,\n"
            "     %s,\n     %s,\n     %s,\n     %s, %s, %s, %s, %s, %s, %s, %s, %s, %d, %d, %s, %s}," % (
                index, cpp_string(s["name"]), cpp_string(s["component"]), cpp_string(s["type"]), s["matchFore"],
                s["matchAft"], s["alwaysOpen"], first_radii, len(s["radii"]), first_column, len(s["columns"]),
                legacy_column, fore_column, aft_column, s["boxes"]["legacy"], s["boxes"]["fore"], s["boxes"]["aft"],
                "true" if fore is not None else "false", fore[0] if fore is not None else "0.0",
                fore[1] if fore is not None else "0.0", "true" if aft is not None else "false", aft_value,
                aft_tolerance, openrocket_aft, cpp_string(s["always"][0]), s["always"][1],
                first_view, len(s["views"]), s["prefs"][0], s["prefs"][1]))

    out.append("/// The symmetric components of every scenario's design, scenario after scenario.")
    table(out, "PresetChooserRadiiPin", "kPresetChooserRadii", radii_rows)
    out.append("")
    out.append("/// The table's columns of every scenario, scenario after scenario.")
    table(out, "PresetChooserColumnPin", "kPresetChooserColumns", column_rows)
    out.append("")
    out.append("/// The views of every scenario, scenario after scenario.")
    table(out, "PresetChooserViewPin", "kPresetChooserViews", view_rows)
    out.append("")
    out.append("/// The scenarios, in the probe's order.")
    table(out, "PresetChooserScenarioPin", "kPresetChooserScenarios", scenario_rows)
    out.append("")
    out.append("/// The actions, in the probe's order.")
    table(out, "PresetChooserActionPin", "kPresetChooserActions", [
        "    {%d, PresetChooserActionKind::%s, %d, %d, %s, %s, %s, %s}," % (
            scenario, kind, row, column, cpp_string(applied), cpp_string(tables), cpp_string(preference), checked)
        for scenario, kind, row, column, applied, tables, preference, checked in data["actions"]])
    out.append("")
    window = data["window"]
    owner_width, owner_height = window["owner"].split("x")
    width, height = window["size"].split("x")
    rows, columns = window["table"].split("x")
    out.append("/// The text the window's table shows no row for.")
    out.append("inline constexpr std::string_view kPresetChooserNoMatchText = %s;" % cpp_string(window["emptyText"]))
    out.append("/// The dialog as a window.")
    out.append("inline constexpr PresetChooserWindowPin kPresetChooserWindow{%d, %d, %d, %d, %d, %s, %s, %d, %d, %d};" % (
        int(window["scenario"]), int(owner_width), int(owner_height), int(width), int(height),
        cpp_string(window["defaultButton"]), boolean(window["escapeCloses"]), int(rows), int(columns),
        int(window["emptyRows"])))
    out.append("/// The window's focus order (Swing's LayoutFocusTraversalPolicy): each component's class and text;")
    out.append("/// the first one has the focus when the dialog opens.")
    table(out, "std::string_view", "kPresetChooserFocusOrder", ["    %s," % cpp_string(d) for d in data["focus"]])
    out.append("/// The keys pressed in the window's table, in the probe's order.")
    table(out, "PresetChooserKeyPin", "kPresetChooserKeys", [
        "    {%s, %d, %d, PresetChooserKey::%s, %d, %d, %d, %d}," % k for k in data["keys"]])
    out.append("")
    out.append(HEADER_BOTTOM)
    with open(header, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    # The repository's style (its .clang-format, wherever the header is written: generate.sh --check
    # writes it into a temporary directory), so that a run reproduces the committed header byte for
    # byte.
    style = pathlib.Path(__file__).resolve().parents[3] / ".clang-format"
    clang_format = os.environ.get("CLANG_FORMAT", "clang-format")
    subprocess.run([clang_format, "-i", f"--style=file:{style}", header], check=True)


if __name__ == "__main__":
    main()

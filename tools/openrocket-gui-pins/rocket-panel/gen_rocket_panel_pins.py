#!/usr/bin/env python3
"""Writes tests/gui/figure/RocketPanelPins.h from RocketPanelProbe's output.

usage: gen_rocket_panel_pins.py OUT.txt HEADER COMMIT

The probe (probe/RocketPanelProbe.java, which generate.sh runs under xvfb-run) prints
SNAP, DRAG, POINT, SELECT and CLICK lines. The CLICK lines are OpenRocket's; where QtRocket
differs on purpose, EDITS below gives QtRocket's expectation and the reason, and the pin keeps
OpenRocket's as javaSelection/javaDialog.
"""

import os
import pathlib
import subprocess
import sys

# Step index (0-based, over SELECT and CLICK lines) -> (label, QtRocket selection, QtRocket dialog,
# replayed click count, reason).
U4 = ("the user's decision U4: a right-click selects the topmost clicked component when none of "
      "them is selected (OpenRocket selects each in turn and ends on the last, the lowest)")
TRIPLE = ("Qt has no triple click: a third quick click is a click of its own (OpenRocket's "
          "CustomClickCountListener counts it as a third, handled as a double-click)")
EDITS = {
    "E right-click stack#0": ("[Engine block]", "-", None, U4),
    "E right-click stack#1": ("[Engine block]", "-", None, U4),
    "E shift-right-click stack#0": ("[Engine block]", "-", None, U4),
    "F third click#0": ("[Engine block]", "-", 1, TRIPLE),
}


def cpp_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def hex_double(text):
    value = float.fromhex(text)
    if value != value:
        return "kNaN"
    if value == float("inf"):
        return "kInfinity"
    if value == float("-inf"):
        return "-kInfinity"
    return text


def main():
    out_path, header_path, commit = sys.argv[1], sys.argv[2], sys.argv[3]
    snaps, drags, points, steps = [], [], [], []
    seen = {}
    with open(out_path, encoding="utf-8") as out:
        for line in out:
            line = line.rstrip("\n")
            if line.startswith("SNAP "):
                _, angle, snapped = line.split()
                snaps.append((hex_double(angle), hex_double(snapped)))
            elif line.startswith("DRAG "):
                _, original, dy, height, shift, rotation = line.split()
                drags.append((original, int(dy), int(height), shift == "1", rotation))
            elif line.startswith("POINT "):
                head, components = line[len("POINT "):].split(" | ")
                name, x, y = head.split()
                points.append((name, x, y, components))
            elif line.startswith("SELECT "):
                label, names, selection = line[len("SELECT "):].split(" | ")
                steps.append(dict(label=label, select=True, names=names, point="", button="",
                                  modifiers="", count=0, selection=selection, dialog="-",
                                  popup=False))
            elif line.startswith("CLICK "):
                label, spec, selection, rest = line[len("CLICK "):].split(" | ", 3)
                dialog, popup = rest.rsplit(" |", 1)
                point, button, modifiers, count = spec.split()
                steps.append(dict(label=label, select=False, names="", point=point, button=button,
                                  modifiers="" if modifiers == "-" else modifiers,
                                  count=int(count), selection=selection, dialog=dialog,
                                  popup=popup.strip() == "popup"))
    used = set()
    for step in steps:
        key_base = step["label"]
        index = seen.get(key_base, 0)
        seen[key_base] = index + 1
        key = f"{key_base}#{index}"
        step["javaSelection"] = ""
        step["javaDialog"] = ""
        step["deviation"] = ""
        if key in EDITS:
            selection, dialog, count, reason = EDITS[key]
            used.add(key)
            step["javaSelection"] = step["selection"]
            step["javaDialog"] = step["dialog"]
            step["selection"] = selection
            step["dialog"] = dialog
            if count is not None:
                step["count"] = count
            step["deviation"] = reason
    missing = set(EDITS) - used
    if missing:
        sys.exit(f"edits not applied: {sorted(missing)}")

    lines = []
    w = lines.append
    w("#pragma once")
    w("")
    w("// GENERATED by tools/openrocket-gui-pins/generate.sh (rocket-panel/gen_rocket_panel_pins.py from")
    w("// the output of rocket-panel/probe/RocketPanelProbe.java: OpenRocket's RocketPanel and")
    w("// ViewRotationControl, made headless with SwingPreferences and FlatLaf Light, run under Xvfb so")
    w("// that the toolkit has a menu shortcut key; see rocket_panel_golden_tests.cpp); do not edit.")
    w("")
    w("#include <array>")
    w("#include <limits>")
    w("#include <ostream>")
    w("#include <string_view>")
    w("")
    w("namespace QtRocket::Gui::Test")
    w("{")
    w("")
    w("/// The OpenRocket commit the pins come from.")
    w(f"inline constexpr std::string_view kRocketPanelPinsCommit = {cpp_string(commit)};")
    w("")
    w("/// ViewRotationControl.snapRotation(angle).")
    w("struct SnapRotationPin")
    w("{")
    w("    double angle;")
    w("    double snapped;")
    w("};")
    w("")
    w("/// RocketPanel.handleMouseDragged(): a left drag from a press with the figure at the rotation")
    w("/// original, dy pixels down, the scroll pane height pixels high, Shift held or not, and the")
    w("/// figure's rotation after it.")
    w("struct DragRotationPin")
    w("{")
    w("    double original;")
    w("    int    dy;")
    w("    int    height;")
    w("    bool   shift;")
    w("    double rotation;")
    w("};")
    w("")
    w("/// A point (x, y) in metres of the side view of \"A simple model rocket\" (settled, rotation 0)")
    w("/// and the components RocketFigure.getComponentsByPoint() gives there, the topmost first.")
    w("struct RocketPanelPointPin")
    w("{")
    w("    std::string_view name;")
    w("    double           x;")
    w("    double           y;")
    w("    std::string_view components;")
    w("};")
    w("")
    w("/// A step of the click transcript on \"A simple model rocket\": the tree selection set to the")
    w("/// components named (select), or a click (RocketPanel.handleMouseClick()) at a point of")
    w("/// kRocketPanelPoints with a button, the modifiers held and the click count (2: the second")
    w("/// click of a double-click), then the selection, the configuration dialog asked for (its")
    w("/// component and the others of a multi-edit; \"-\" for none) and whether the popup menu was")
    w("/// asked for. Where QtRocket differs on purpose, selection and dialog are QtRocket's, and")
    w("/// javaSelection and javaDialog OpenRocket's, with the reason in deviation.")
    w("struct RocketPanelStepPin")
    w("{")
    w("    std::string_view label;")
    w("    bool             select;")
    w("    std::string_view names;")
    w("    std::string_view point;")
    w("    std::string_view button;")
    w("    std::string_view modifiers;")
    w("    int              count;")
    w("    std::string_view selection;")
    w("    std::string_view dialog;")
    w("    bool             popup;")
    w("    std::string_view javaSelection;")
    w("    std::string_view javaDialog;")
    w("    std::string_view deviation;")
    w("};")
    w("")
    w("// NOLINTNEXTLINE(readability-identifier-naming): the name GoogleTest looks for")
    w("inline void PrintTo(const RocketPanelStepPin& pin, std::ostream* out)")
    w("{")
    w("    *out << pin.label;")
    w("}")
    w("")
    w("inline constexpr double kNaN      = std::numeric_limits<double>::quiet_NaN();")
    w("inline constexpr double kInfinity = std::numeric_limits<double>::infinity();")
    w("")
    w("// NOLINTBEGIN(modernize-use-designated-initializers): tables printed by the Java probe")
    w("// NOLINTBEGIN(modernize-use-std-numbers): the doubles as the probe printed them")
    w("inline constexpr auto kSnapRotationPins = std::to_array<SnapRotationPin>({")
    for angle, snapped in snaps:
        w(f"    {{{angle}, {snapped}}},")
    w("});")
    w("")
    w("inline constexpr auto kDragRotationPins = std::to_array<DragRotationPin>({")
    for original, dy, height, shift, rotation in drags:
        w(f"    {{{original}, {dy}, {height}, {'true' if shift else 'false'}, {rotation}}},")
    w("});")
    w("")
    w("inline constexpr auto kRocketPanelPoints = std::to_array<RocketPanelPointPin>({")
    for name, x, y, components in points:
        w(f"    {{{cpp_string(name)}, {x}, {y}, {cpp_string(components)}}},")
    w("});")
    w("")
    w("inline constexpr auto kRocketPanelSteps = std::to_array<RocketPanelStepPin>({")
    for s in steps:
        w("    {" + ", ".join([
            cpp_string(s["label"]), "true" if s["select"] else "false", cpp_string(s["names"]),
            cpp_string(s["point"]), cpp_string(s["button"]), cpp_string(s["modifiers"]),
            str(s["count"]), cpp_string(s["selection"]), cpp_string(s["dialog"]),
            "true" if s["popup"] else "false", cpp_string(s["javaSelection"]),
            cpp_string(s["javaDialog"]), cpp_string(s["deviation"])]) + "},")
    w("});")
    w("// NOLINTEND(modernize-use-std-numbers)")
    w("// NOLINTEND(modernize-use-designated-initializers)")
    w("")
    w("}  // namespace QtRocket::Gui::Test")
    w("")
    with open(header_path, "w", encoding="utf-8", newline="\n") as header:
        header.write("\n".join(lines))
    # The repository's style (its .clang-format, wherever the header is written: generate.sh
    # --check writes it into a temporary directory), so that a run reproduces the committed
    # header byte for byte.
    style = pathlib.Path(__file__).resolve().parents[3] / ".clang-format"
    clang_format = os.environ.get("CLANG_FORMAT", "clang-format")
    subprocess.run([clang_format, "-i", f"--style=file:{style}", header_path], check=True)


if __name__ == "__main__":
    main()

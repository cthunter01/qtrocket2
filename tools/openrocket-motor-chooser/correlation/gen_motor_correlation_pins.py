#!/usr/bin/env python3
"""Writes tests/core/motor/MotorCorrelationPins.h from MotorCorrelationProbe's output.

usage: gen_motor_correlation_pins.py PROBE_OUTPUT HEADER COMMIT

PROBE_OUTPUT is the probe's standard output (generate.sh sends OpenRocket's log to standard error): the
SAMPLES line, the DATABASE line, then per motor set of more than one curve a SET line, a CURVE line per
curve and a PAIR line per ordered pair of two different curves (fields separated by tabs; see the probe's
comment). Every double goes into the header as the C++ hexadecimal floating literal of its
Double.toHexString (exact), the similarity's Double.toString also in a comment. The generator refuses a
transcript whose lines do not fit together, and a non-finite value.
"""
import os
import pathlib
import subprocess
import sys

HEADER_TOP = """#pragma once

// GENERATED by tools/openrocket-motor-chooser/generate.sh (from the output of
// correlation/probe/MotorCorrelationProbe.java by correlation/gen_motor_correlation_pins.py):
// OpenRocket's MotorCorrelation over the thrust curves of data/motors/initial_motors.db (see
// MotorCorrelationPinsGolden in MotorCorrelationTests.cpp). Do not edit. Test-only.

#include <array>
#include <cstddef>
#include <string_view>

namespace QtRocket::Test
{{

/// The OpenRocket commit the pins come from.
inline constexpr std::string_view kMotorCorrelationPinsCommit = "{commit}";

/// How many times MotorCorrelation.crossCorrelation() asks each motor for its thrust.
inline constexpr std::size_t kCorrelationPinsSampleCount = {sample_count};

/// The second of those times (the first is 0).
inline constexpr double kCorrelationPinsSecondSampleTime = {second_time};

/// The last of them.
inline constexpr double kCorrelationPinsLastSampleTime = {last_time};

/// Their sum, added in the order they are asked.
inline constexpr double kCorrelationPinsSampleTimeSum = {time_sum};

/// The thrust curves ThrustCurveMotorSQLiteDatabase.readDatabase() returned for the database.
inline constexpr std::size_t kCorrelationPinsCurvesRead = {curves};

/// The motor sets ThrustCurveMotorSetDatabase.addMotor() made of them, in all.
inline constexpr std::size_t kCorrelationPinsMotorSets = {sets};

/// The curves those motor sets hold, in all.
inline constexpr std::size_t kCorrelationPinsMotors = {motors};

/// A motor set of more than one curve.
struct MotorCorrelationSetPin
{{
    /// Its index in ThrustCurveMotorSetDatabase.getMotorSets().
    std::size_t setIndex;
    /// The display name of its manufacturer.
    std::string_view manufacturer;
    /// Its designation.
    std::string_view designation;
    /// How many curves it holds.
    std::size_t curveCount;
    /// The index of the digest of its first curve in kMotorCorrelationDigestPins; the digests of the
    /// others follow, in the order of ThrustCurveMotorSet.getMotors().
    std::size_t firstDigest;
}};

/// What OpenRocket's MotorCorrelation gives for an ordered pair of two different curves of a set.
struct MotorCorrelationPairPin
{{
    /// The set: an index into kMotorCorrelationSetPins.
    std::size_t set;
    /// The first curve: an index into the set's getMotors().
    std::size_t first;
    /// The second curve.
    std::size_t second;
    /// MotorCorrelation.similarity(first, second).
    double similarity;
    /// MotorCorrelation.crossCorrelation(first, second).
    double crossCorrelation;
}};

// NOLINTBEGIN(modernize-use-designated-initializers): tables printed by the Java probe
// NOLINTBEGIN(modernize-use-std-numbers): Java's values, some of them near a constant
"""

HEADER_BOTTOM = """// NOLINTEND(modernize-use-std-numbers)
// NOLINTEND(modernize-use-designated-initializers)

}  // namespace QtRocket::Test
"""


def cpp_string(text):
    out = []
    for ch in text:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= code < 0x7F:
            out.append(ch)
        else:
            # UTF-8 bytes as escapes (the core's texts are UTF-8 std::string), each literal ending after
            # them so that no following character continues an escape.
            for byte in ch.encode("utf-8"):
                out.append("\\x%02X" % byte)
            out.append('" "')
    literal = '"' + "".join(out) + '"'
    # No empty literal after a final escape.
    return literal[:-4] + '"' if literal.endswith('" ""') else literal


def ascii_comment(text):
    """@p text for a comment: ASCII, anything else as Python's backslash escapes."""
    return text.encode("ascii", "backslashreplace").decode("ascii")


def hex_literal(text):
    """The C++ literal of a Double.toHexString of a finite double."""
    value = float.fromhex(text)  # Java's "NaN" and "Infinity" too, which no pin may hold
    if value != value or value in (float("inf"), float("-inf")):
        sys.exit("error: a non-finite value in the transcript: " + text)
    return text


def fail(line_number, message):
    sys.exit("error: line %d of the transcript: %s" % (line_number, message))


def parse(lines):
    samples = None
    database = None
    sets = []
    for number, raw in enumerate(lines, 1):
        line = raw.rstrip("\n")
        if not line:
            continue
        fields = line.split("\t")
        kind = fields[0]
        if kind == "SAMPLES":
            if samples is not None or database is not None or len(fields) != 5:
                fail(number, "a second, late or malformed SAMPLES line")
            samples = (int(fields[1]), hex_literal(fields[2]), hex_literal(fields[3]), hex_literal(fields[4]))
        elif kind == "DATABASE":
            if samples is None or database is not None or len(fields) != 4:
                fail(number, "a second, early or malformed DATABASE line")
            database = tuple(int(f) for f in fields[1:])
        elif kind == "SET":
            if database is None or len(fields) != 5:
                fail(number, "a SET line before DATABASE, or malformed")
            set_index, count = int(fields[1]), int(fields[4])
            if count < 2 or (sets and set_index <= sets[-1]["index"]):
                fail(number, "a set of fewer than two curves, or out of order")
            sets.append({"index": set_index, "manufacturer": fields[2], "designation": fields[3],
                         "count": count, "digests": [], "pairs": []})
        elif kind == "CURVE":
            if not sets or len(fields) != 4 or int(fields[1]) != sets[-1]["index"] or \
                    int(fields[2]) != len(sets[-1]["digests"]):
                fail(number, "a CURVE line out of place")
            sets[-1]["digests"].append(fields[3])
        elif kind == "PAIR":
            if not sets or len(fields) != 8 or int(fields[1]) != sets[-1]["index"]:
                fail(number, "a PAIR line out of place")
            current = sets[-1]
            first, second = int(fields[2]), int(fields[3])
            expected = [(i, j) for i in range(current["count"]) for j in range(current["count"]) if i != j]
            if len(current["pairs"]) >= len(expected) or expected[len(current["pairs"])] != (first, second):
                fail(number, "a PAIR line out of order")
            if float.fromhex(fields[4]) != float(fields[5]) or float.fromhex(fields[6]) != float(fields[7]):
                fail(number, "the hexadecimal and decimal values differ")
            current["pairs"].append((first, second, fields[4], fields[5], fields[6], fields[7]))
        else:
            fail(number, "an unknown line")
    if samples is None or database is None:
        sys.exit("error: no SAMPLES or DATABASE line in the transcript")
    for current in sets:
        if len(current["digests"]) != current["count"] or \
                len(current["pairs"]) != current["count"] * (current["count"] - 1):
            sys.exit("error: set %d lacks curves or pairs" % current["index"])
    return samples, database, sets


def main():
    probe, header, commit = sys.argv[1:4]
    with open(probe, encoding="utf-8") as f:
        samples, database, sets = parse(f.readlines())
    out = [HEADER_TOP.format(commit=commit, sample_count=samples[0], second_time=samples[1], last_time=samples[2],
                             time_sum=samples[3], curves=database[0], sets=database[1], motors=database[2])]
    out.append("/// The motor sets of more than one curve, in the order of getMotorSets().")
    out.append("inline constexpr auto kMotorCorrelationSetPins = std::to_array<MotorCorrelationSetPin>({")
    first_digest = 0
    for s in sets:
        out.append("    {%d, %s, %s, %d, %d}," % (s["index"], cpp_string(s["manufacturer"]),
                                                cpp_string(s["designation"]), s["count"], first_digest))
        first_digest += s["count"]
    out.append("});")
    out.append("")
    out.append("/// The digests of the curves of the sets, set by set.")
    out.append("inline constexpr auto kMotorCorrelationDigestPins = std::to_array<std::string_view>({")
    for s in sets:
        out.append("    // %s %s (set %d)" % (ascii_comment(s["manufacturer"]), ascii_comment(s["designation"]),
                                            s["index"]))
        for digest in s["digests"]:
            out.append("    %s," % cpp_string(digest))
    out.append("});")
    out.append("")
    out.append("/// Every ordered pair of two different curves of each set, set by set, in the order (0, 1), (0, 2),")
    out.append("/// ..., (1, 0), (1, 2), ...; the comments hold the similarity as Java's Double.toString writes it.")
    out.append("inline constexpr auto kMotorCorrelationPairPins = std::to_array<MotorCorrelationPairPin>({")
    for position, s in enumerate(sets):
        out.append("    // %s %s (set %d)" % (ascii_comment(s["manufacturer"]), ascii_comment(s["designation"]),
                                            s["index"]))
        for first, second, similarity_hex, similarity, cross_hex, _ in s["pairs"]:
            out.append("    {%d, %d, %d, %s, %s},  // %s" % (
                position, first, second, hex_literal(similarity_hex), hex_literal(cross_hex), similarity))
    out.append("});")
    out.append("")
    out.append(HEADER_BOTTOM)
    with open(header, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    # The repository's style (its .clang-format, wherever the header is written: generate.sh --check writes
    # it into a temporary directory), so that a run reproduces the committed header byte for byte.
    style = pathlib.Path(__file__).resolve().parents[3] / ".clang-format"
    clang_format = os.environ.get("CLANG_FORMAT", "clang-format")
    subprocess.run([clang_format, "-i", f"--style=file:{style}", header], check=True)


if __name__ == "__main__":
    main()
